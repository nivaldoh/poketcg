# ## Overall game plan

# Your default attacker is **Lillie’s Clefairy ex**. Its Full Moon Rondo does:

# **20 + 20 damage for every Benched Pokémon on both sides.**

# Area Zero Underdepths lets you have eight Benched Pokémon while you have a Tera Pokémon in play, with Wellspring Ogerpon ex and Koraidon ex serving as your Tera enablers. ([Limitless TCG][3])

# Useful damage thresholds:

# | Total Benched Pokémon | Damage |
# | --------------------: | -----: |
# |                     8 |    180 |
# |                    10 |    220 |
# |                    11 |    240 |
# |                    12 |    260 |
# |                    13 |    280 |

# Clefairy also changes the Weakness of opposing Dragon Pokémon to Psychic, meaning it can double these numbers against Dragons. This is particularly valuable against Dragapult decks. ([Limitless TCG][3])

# ## How to pilot it

# ### Before the game

# **Usually choose to go second.** That lets you play Crispin immediately. Crispin finds two differently typed Basic Energy, attaches one, and places the other in your hand. Combined with your normal attachment, it can power up Clefairy’s two-Energy attack in one turn. ([Limitless TCG][4])

# ### First-turn priorities

# 1. **Get Latias ex into play.**
#    Its Skyliner Ability removes the Retreat Cost of all your Basic Pokémon, allowing Kangaskhan, Clefairy, Meowth and your situational attackers to move freely. ([Limitless TCG][5])

# 2. **Bench Meowth ex.**
#    When played from your hand, Meowth searches for any Supporter. Most commonly, take **Crispin** for an immediate attack. Later, take Boss’s Orders, Ciphermaniac or Cyrano. ([Limitless TCG][6])

# 3. **Find Lillie’s Clefairy ex and begin powering it.**

# 4. **Bench a Tera Pokémon before playing Area Zero.**
#    Usually this is Wellspring Ogerpon. Once Area Zero is active, fill enough Bench spaces to reach the damage number you need.

# 5. **Attack with Full Moon Rondo.**

# An ideal start is Mega Kangaskhan ex Active, Latias on the Bench, and Clefairy being powered up. Kangaskhan’s Run Errand draws two cards while it is Active; Latias then lets it retreat for free. ([Limitless TCG][7])

# ### Midgame loop

# After the first attack:

# * Prepare a second Clefairy before the Active one is knocked out.
# * Attach **Lillie’s Pearl** to Clefairy whenever possible. If that Clefairy is knocked out by attack damage, the opponent takes one fewer Prize card. ([Limitless TCG][8])
# * After one of your Pokémon is knocked out, use Fezandipiti ex to draw three cards. ([Limitless TCG][9])
# * Use Boss’s Orders or Prime Catcher to target a vulnerable two-Prize Pokémon rather than repeatedly hitting a large Active Pokémon.
# * Keep one Bench space available when possible so you can trigger a new Meowth or Fezandipiti.

# **Important Wondrous Patch sequencing:** it attaches a Basic Psychic Energy from the discard pile to a **Benched Psychic Pokémon**. Ultra Ball can discard the Psychic Energy first, but Clefairy must still be on the Bench when you use the Patch. ([Limitless TCG][10])

# ### Situational attackers

# You can learn these after becoming comfortable with the main Clefairy plan:

# * **Mega Kangaskhan ex:** dependable 200 base damage, 300 HP and extra damage from coin flips. Treat anything beyond 200 as a bonus, not part of your plan. ([Limitless TCG][7])
# * **Koraidon ex:** after your opponent knocks out one of your Pokémon, Orichalcum Fang rises from 50 to 170 damage. ([Limitless TCG][11])
# * **Wellspring Ogerpon ex:** can do 100 damage to the Active and 120 to a Benched Pokémon by returning three Energy to the deck. Useful for finishing damaged support Pokémon. ([Limitless TCG][12])
# * **Moltres:** a single-Prize attacker that deals 110 damage against Pokémon ex. ([Limitless TCG][13])
# * **Chien-Pao:** mainly a searchable way to discard a troublesome Stadium when you bench it. ([Limitless TCG][14])

# ## Strengths

# **Extremely consistent setup.** Every Pokémon is Basic, and the deck runs four Meowth, four Ultra Ball, four Dusk Ball and Cyrano.

# **Can attack immediately.** Crispin plus the normal attachment can power Clefairy in one turn.

# **Excellent mobility.** Latias gives all your Pokémon free retreat.

# **Strong Prize trade.** Lillie’s Pearl can turn Clefairy into an effective one-Prize attacker.

# **Flexible damage.** Clefairy handles most normal attacks, while Kangaskhan, Koraidon and Ogerpon cover unusual board states.

# **Especially strong against Dragons.** Clefairy’s Fairy Zone changes their Weakness to Psychic.

# ## Weaknesses

# **Clefairy is fragile.** It has only 190 HP and Metal Weakness, so many decks can knock it out in one attack. ([Limitless TCG][3])

# **Damage depends on both Benches.** Opponents who deliberately keep a small Bench can prevent you from reaching 240–280 damage.

# **Area Zero management matters.** If Area Zero leaves play, you must reduce your Bench to five Pokémon. This can remove support Pokémon and immediately reduce Clefairy’s damage. ([Limitless TCG][15])

# **The Bench contains attractive targets.** Meowth, Fezandipiti and Latias can be pulled Active for easy Prizes.

# **Mixed Energy can punish mistakes.** Before attaching an Energy, decide whether your next attacker will be Clefairy, Kangaskhan, Koraidon or Ogerpon.

# **Some of its NAIC success was metagame-dependent.** It was exceptionally well positioned against the many Dragon-based Dragapult decks. It remains a legitimate competitive deck, but its advantage becomes smaller when Dragon decks decline.

# The most important beginner rule is: **default to Clefairy, count the Benches, and only use the alternative attackers when they clearly produce a better knockout or Prize trade.**

