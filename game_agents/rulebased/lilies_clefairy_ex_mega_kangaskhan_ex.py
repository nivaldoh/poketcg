def _damage_shield(defender: Pokemon) -> int:
    """Worst-case flat damage reduction the defender may have up ("takes N less damage" attack
    riders, e.g. Mega Abomasnow's Frost Barrier). We can't see whether it was actually used last
    turn, so assume it when the attack is payable."""
    best = 0
    for aid in card_table[defender.id].attacks:
        a = attack_table.get(aid)
        if a is None or len(defender.energies) < len(a.energies):
            continue
        m = re.search(r"takes (\d+) less damage", a.text or "")
        if m:
            best = max(best, int(m.group(1)))
    return best


def _est_attack_dmg(op_state, attacker: Pokemon, attack) -> int:
    """Estimated REAL damage of an opponent attack: base damage plus a text-derived guess for
    "damage for each ..." scaling (which the metadata reports as base 0-20 — Hammer-lanche,
    Riptide, Voltaic Chain, Bellowing Thunder all read as harmless to a base-damage check).
    Counting tiers, most-specific first; sources we can't see (their deck top) use a fixed 3."""
    dmg = attack.damage or 0
    text = attack.text or ""
    m = re.search(r"(\d+)(?: more)? damage for each", text)
    if not m:
        return dmg
    per = int(m.group(1))
    board = [p for p in list(op_state.active or []) + list(op_state.bench) if p is not None]
    if "for each heads" in text:
        n = 1  # geometric coin flips: expect one head
    elif "Energy attached to both Active" in text:
        n = len(attacker.energies)  # plus ours, which we can't know here — undercount is fine
    elif "Energy attached" in text:
        n = sum(len(p.energies) for p in board)
    elif "in your discard pile" in text:
        n = sum(1 for c in op_state.discard
                if card_table.get(c.id) is not None and card_table[c.id].hp == 0
                and c.id < 20)  # basic energy cards (cardId == its EnergyType value)
    elif "Benched Pokémon" in text:
        n = sum(1 for p in list(op_state.bench) if p is not None)  # ours not visible here; undercount
    elif "Pokémon in play" in text:
        n = len(board)
    else:
        n = 3  # hidden source (e.g. Hammer-lanche's top-6 discard)
    return dmg + per * n


def _weak_mult(defender: Pokemon, atk_type, fairy_zone: bool) -> tuple[int, int]:
    """(weakness multiplier, resistance subtraction) for an attack of `atk_type` into `defender`.
    The obs Pokemon has no live weakness field, so Fairy Zone's Dragon->{P} rewrite is applied
    here in code."""
    data = card_table[defender.id]
    weak = data.weakness
    if fairy_zone and data.energyType == EnergyType.DRAGON:
        weak = EnergyType.PSYCHIC
    mult = 2 if (weak is not None and atk_type is not None and weak == atk_type) else 1
    res = 30 if (data.resistance is not None and atk_type is not None
                 and data.resistance == atk_type) else 0
    return mult, res


def _can_pay(p: Pokemon, attack) -> bool:
    """Count+type payability estimate for a candidate attacker (the engine decides for real when
    it offers the ATTACK option). p.energies lists provided EnergyTypes (Telepath shows as {P})."""
    need = list(attack.energies)
    have = list(p.energies)
    if len(have) < len(need):
        return False
    for t in set(need):
        if t == EnergyType.COLORLESS:
            continue
        if have.count(t) < need.count(t):
            return False
    return True


def _attack_damage(attack_id: int, my_state, op_state, defender: Pokemon | None,
                   fairy_zone: bool, attacker: Pokemon | None = None,
                   opp_bench_delta: int = 0) -> int:
    """Expected damage of an attack into `defender`, weakness applied. Coin-flip attacks use
    their guaranteed base. Cruel Arrow / Pump bench hits are effect damage (no weakness).
    `opp_bench_delta` adjusts Rondo's bench count for a hypothetical gust (-1 bench there)."""
    if defender is None:
        return 0
    base, atk_type = 0, None
    if attack_id == ATK_RONDO:
        benched = (sum(1 for p in my_state.bench if p is not None)
                   + sum(1 for p in op_state.bench if p is not None) + opp_bench_delta)
        base, atk_type = 20 + 20 * max(0, benched), EnergyType.PSYCHIC
    elif attack_id == ATK_RAPID_FIRE:
        base, atk_type = 200, EnergyType.COLORLESS
    elif attack_id == ATK_EON_BLADE:
        base, atk_type = 200, EnergyType.PSYCHIC
    elif attack_id == ATK_PUMP:
        base, atk_type = 100, EnergyType.WATER
    elif attack_id == ATK_CRUEL_ARROW:
        return 100  # effect damage: no weakness/resistance
    elif attack_id == ATK_FIGHTING_WINGS:
        d = card_table.get(defender.id)
        base = 20 + (90 if d is not None and (d.ex or d.megaEx) else 0)
        atk_type = EnergyType.FIRE
    elif attack_id == ATK_ICICLE_LOOP:
        base, atk_type = 120, EnergyType.WATER
    elif attack_id == ATK_ORICHALCUM:
        base, atk_type = 50 + (120 if was_koed else 0), EnergyType.FIGHTING
    elif attack_id == ATK_IMPACT_BLOW:
        base, atk_type = 200, EnergyType.FIGHTING
    elif attack_id == ATK_TUCK_TAIL:
        base, atk_type = 60, EnergyType.COLORLESS
    elif attack_id == ATK_SOB:
        base, atk_type = 20, EnergyType.WATER
    else:
        return 0
    mult, res = _weak_mult(defender, atk_type, fairy_zone)
    return max(0, base * mult - res)


def _best_payable_dmg(p: Pokemon, my_state, op_state, defender: Pokemon | None,
                      fairy_zone: bool, opp_bench_delta: int = 0) -> int:
    """Best damage among p's payable attacks into `defender` (base damage when no defender)."""
    best = 0
    data = card_table.get(p.id)
    if data is None:
        return 0
    for aid in data.attacks:
        a = attack_table.get(aid)
        if a is None or not _can_pay(p, a):
            continue
        if defender is not None:
            best = max(best, _attack_damage(aid, my_state, op_state, defender, fairy_zone, p,
                                            opp_bench_delta))
        else:
            best = max(best, a.damage or 20)
    return best


def _opp_big_hitter(op_state) -> bool:
    """Cheap 2HKO pressure proxy: anything on their board with a >=150 BASE damage attack makes
    a benched 300HP/3-prize Kangaskhan a 2-hit gift. Variable attacks (base 0) don't trip this."""
    return any(attack_table[aid].damage >= 150
               for p in list(op_state.active or []) + list(op_state.bench)
               if p is not None and p.id in card_table
               for aid in card_table[p.id].attacks if aid in attack_table)


def _opp_can_ohko(op_state, our_hp: int) -> bool:
    """Whether the opponent's ACTIVE has a payable attack whose estimated REAL damage one-shots
    `our_hp`. Uses _est_attack_dmg: the base-damage-only version was blind to exactly the
    scaling attacks (Hammer-lanche base 0, Voltaic Chain base 20) that OHKO our whole deck, so
    the promote penalty never fired in those matchups. Deliberately active-only and un-padded:
    a bench-and-ramp-aware worst-case version measured WORSE (iono h2h 25%->12%, n=100 each) —
    penalizing every promote equally destroys the wall/stall value of a dry 300HP Kangaskhan
    into a not-yet-ramped board."""
    act = op_state.active[0] if op_state.active and op_state.active[0] is not None else None
    if act is None or act.id not in card_table:
        return False
    for aid in card_table[act.id].attacks:
        a = attack_table.get(aid)
        if a is not None and len(act.energies) >= len(a.energies) \
                and _est_attack_dmg(op_state, act, a) >= our_hp:
            return True
    return False


def _reachable_attackers(my_state, latias_in_play: bool) -> list[Pokemon]:
    """Attackers that can occupy the Active Spot this turn: the current active plus, when the
    active's retreat is free or payable, every benched Pokémon (Skyliner = all Basics free)."""
    out = []
    act = my_state.active[0] if my_state.active else None
    if act is not None:
        out.append(act)
    can_rotate = (act is None or latias_in_play or card_table[act.id].retreatCost == 0
                  or len(act.energies) >= card_table[act.id].retreatCost)
    if can_rotate:
        for p in my_state.bench:
            if p is not None:
                out.append(p)
    return out


def _kill_options(my_state, op_state, fairy_zone: bool, latias_in_play: bool) -> dict:
    """What we could KO right now — the current defender and the best gustable bench target —
    using the best payable attack among the active and retreat-reachable bench attackers.
    Bench targets get Rondo evaluated at their-bench-minus-one (the gust moves them out of it)."""
    attackers = _reachable_attackers(my_state, latias_in_play)
    my_need = len(my_state.prize)
    out = {"act_kill": False, "act_prizes": 0, "act_wins": False,
           "bench_i": -1, "bench_prizes": 0, "bench_wins": False}
    act = op_state.active[0] if op_state.active and op_state.active[0] is not None else None
    opp_bench_empty = not any(p is not None for p in op_state.bench)
    if act is not None and any(_best_payable_dmg(p, my_state, op_state, act, fairy_zone)
                               >= act.hp + _damage_shield(act) for p in attackers):
        out["act_kill"] = True
        out["act_prizes"] = prize_count(act)
        # KOing the active with an empty bench is a bench-out win regardless of prizes.
        out["act_wins"] = out["act_prizes"] >= my_need or opp_bench_empty
    best = -1
    best_key = None
    for i, p in enumerate(op_state.bench):
        if p is None:
            continue
        if not any(_best_payable_dmg(q, my_state, op_state, p, fairy_zone, opp_bench_delta=-1)
                   >= p.hp + _damage_shield(p) for q in attackers):
            continue
        pr = prize_count(p)
        # Same tiebreak as the SWITCH gust pick (energized engine piece > empty body) so the
        # "gust is worth it" decision and the actual target choice can't disagree.
        key = (pr, 200 * len(p.energies) + p.hp // 10)
        if best_key is None or key > best_key:
            best_key = key
            out["bench_prizes"] = pr
            best = i
    out["bench_i"] = best
    out["bench_wins"] = out["bench_prizes"] >= my_need
    # A gust is worth it when it converts a KO the current defender doesn't offer, or a bigger
    # one — but never when killing the current active already wins the game.
    out["gust_worth"] = (best >= 0 and not out["act_wins"]
                         and (out["bench_wins"] or not out["act_kill"]
                              or out["bench_prizes"] > out["act_prizes"]))
    return out


def _finish(scores: list[int], select, want: int | None = None) -> list[int]:
    """Sort options by score desc and return the top-k indices; k defaults to maxCount and is
    always clamped into [minCount, maxCount]."""
    order = sorted(range(len(scores)), key=lambda i: (-scores[i], i))
    k = select.maxCount if want is None else want
    k = max(select.minCount, min(select.maxCount, k))
    return order[:k]


def _energy_target_score(target: Pokemon, et, ctx: dict) -> int:
    """0-1000 desirability of placing an `et`-type energy on `target` (shared by the manual
    ATTACH pair, Crispin's ATTACH_FROM half and Wondrous Patch). Clefairy's Rondo cost is
    {P}{C}: the second slot takes ANY type, so surplus of every color feeds the next Clefairy."""
    cid = target.id
    n = len(target.energies)
    has_p = EnergyType.PSYCHIC in target.energies
    if cid == Lillie_Clefairy_ex:
        if et == EnergyType.PSYCHIC:
            if not has_p:
                return 1000
            return 800 if n < 2 else 150  # beyond {P}{C} the fuel is dead weight
        if has_p and n < 2:
            return 950  # completes Full Moon Rondo right now
        if n == 0:
            return 140  # generic first energy: still needs a {P} later — banking Kangaskhan's
                        # {C}{C}{C} (180) beats this (measured 0-6 loss vs random: two {W} died
                        # on a Clefairy that never attacked)
        return 100
    if cid == Latias_ex:
        if et == EnergyType.PSYCHIC:
            return 380 if n < 3 else 100  # the Eon Blade line
        return 200 if n < 3 else 80
    if cid == Wellspring_Ogerpon_ex:
        if et == EnergyType.WATER and EnergyType.WATER not in target.energies:
            return 700
        return 250 if n < 3 else 80  # Pump's {C}{C} slots
    if cid == Koraidon_ex:
        if et == EnergyType.FIGHTING and target.energies.count(EnergyType.FIGHTING) < 2:
            # Weakness-lever matchup (fighting-weak wall on their board): arming Koraidon is
            # the plan once a Rondo attacker is live — 940 sits below "complete a Clefairy
            # right now" (950/1000) but above every other routing.
            if ctx["koraidon_lever"] and ctx["clefairy_powered"]:
                return 940
            return 650
        if ctx["koraidon_lever"] and n < 3:
            return 400  # Impact Blow's third ({C}) slot
        return 220 if n < 3 else 80
    if cid == Moltres:
        if et == EnergyType.FIRE and n < 1:
            return 600 if ctx["opp_ex_board"] else 200
        return 60
    if cid == Chien_Pao:
        return 240 if et == EnergyType.WATER and n < 3 else 60
    if cid == Mega_Kangaskhan_ex:
        if ctx["p_bricked"]:
            return 500 if n < 3 else 150  # Rondo bricked: Rapid-Fire {C}{C}{C} is the plan
        return 180 if n < 3 else 60
    if cid == Fezandipiti_ex:
        return 170 if n < 3 else 50  # Cruel Arrow {C}{C}{C}
    if cid == Meowth_ex:
        return 90
    return 50


def agent(obs_dict: dict) -> list[int]:
    """Main Agent Function.

    Each element in the returned list must be >= 0 and < len(obs.select.option).
    The list length must be between obs.select.minCount and obs.select.maxCount (inclusive),
    with no duplicate elements.

    Returns:
        list[int]: A list of option index.
    """
    global pre_turn, pending_attach_type, opp_prize_prev, was_koed

    obs = to_observation_class(obs_dict)
    if obs.select is None:
        # Kaggle flow first call: return the deck and reset per-game state.
        pre_turn = -1
        pending_attach_type = None
        opp_prize_prev = None
        was_koed = False
        return my_deck

    state = obs.current
    select = obs.select
    context = select.context
    my_index = state.yourIndex
    my_state = state.players[my_index]
    op_state = state.players[1 - my_index]

    if state.turn != pre_turn:
        # New turn: refresh the was-KO'd flag (their prize count dropping since our last look
        # means one of ours went down — the obs has no direct flag for Orichalcum's condition).
        was_koed = opp_prize_prev is not None and len(op_state.prize) < opp_prize_prev
        opp_prize_prev = len(op_state.prize)
        pre_turn = state.turn
        pending_attach_type = None

    eff = select.effect
    eff_id = eff.id if eff is not None else 0

    # ---- board census ----------------------------------------------------------------------
    mine = _my_pokemon(my_state)
    field_counts = defaultdict(int)
    for _, _, p in mine:
        field_counts[p.id] += 1
    hand_counts = defaultdict(int)
    for c in my_state.hand:
        hand_counts[c.id] += 1
    discard_counts = defaultdict(int)
    for c in my_state.discard:
        discard_counts[c.id] += 1
    attached_counts = defaultdict(int)
    for _, _, p in mine:
        for ec in p.energyCards:
            attached_counts[ec.id] += 1

    stadium_id = 0
    for c in state.stadium:
        stadium_id = c.id

    latias_in_play = field_counts[Latias_ex] > 0
    tera_count = field_counts[Wellspring_Ogerpon_ex] + field_counts[Koraidon_ex]
    tera_in_play = tera_count > 0
    benched_count = sum(1 for p in my_state.bench if p is not None)
    bench_room = my_state.benchMax - benched_count
    total_in_play = len(mine)
    supporter_in_hand = any(card_table[c.id].cardType == CardType.SUPPORTER for c in my_state.hand)

    opp_field = [p for p in list(op_state.active or []) + list(op_state.bench) if p is not None]
    opp_has_dragon = any(p.id in card_table
                         and card_table[p.id].energyType == EnergyType.DRAGON for p in opp_field)
    opp_ex_board = any(p.id in card_table and (card_table[p.id].ex or card_table[p.id].megaEx)
                       for p in opp_field)
    opp_big_hitter = _opp_big_hitter(op_state)
    # A fighting-weak WALL (printed HP >= 250: Bellibolt ex 280, Mega Kangaskhan 300) on their
    # board makes Koraidon our weakness lever: Impact Blow 200x2 OHKOs what Rondo can't reach.
    # HP-gated so 170-210HP support exes (Meowth/Fez) don't divert the {F} plan.
    opp_fighting_weak_wall = any(
        p.id in card_table and card_table[p.id].weakness == EnergyType.FIGHTING
        and card_table[p.id].hp >= 250 and prize_count(p) >= 2 for p in opp_field)
    fairy_zone = field_counts[Lillie_Clefairy_ex] > 0 and opp_has_dragon
    opp_stadium_threat = stadium_id != 0 and stadium_id != Area_Zero_Underdepths

    deck_energy_by_id = {e: max(0, DECK_ENERGY_TOTALS[e] - hand_counts[e] - discard_counts[e]
                                - attached_counts[e]) for e in ENERGY_IDS}
    deck_energy_left = sum(deck_energy_by_id.values())

    clefairys = [p for _, _, p in mine if p.id == Lillie_Clefairy_ex]
    clefairy_powered = any(len(p.energies) >= 2 and EnergyType.PSYCHIC in p.energies
                           for p in clefairys)
    clefairy_needs_p = any(EnergyType.PSYCHIC not in p.energies for p in clefairys)
    clefairy_incomplete = any(len(p.energies) < 2 or EnergyType.PSYCHIC not in p.energies
                              for p in clefairys)
    ogerpon_needs_water = any(p.id == Wellspring_Ogerpon_ex
                              and EnergyType.WATER not in p.energies for _, _, p in mine)
    koraidon_needs_f = any(p.id == Koraidon_ex and EnergyType.FIGHTING not in p.energies
                           for _, _, p in mine)
    # {P} hard-bricked: no Clefairy holds a {P} and none is reachable from any zone — the Rondo
    # plan is dead and Kangaskhan's {C}{C}{C} becomes the win condition.
    p_bricked = (not any(EnergyType.PSYCHIC in p.energies for p in clefairys)
                 and deck_energy_by_id[Psychic_Energy] == 0
                 and hand_counts[Psychic_Energy] + hand_counts[Telepath_Energy] == 0
                 and discard_counts[Psychic_Energy] == 0)
    # Basic {P} Pokémon plausibly still in the deck (Telepath-rider value; prizes ignored).
    deck_p_mons = (max(0, 4 - field_counts[Lillie_Clefairy_ex] - hand_counts[Lillie_Clefairy_ex]
                       - discard_counts[Lillie_Clefairy_ex])
                   + max(0, 3 - field_counts[Latias_ex] - hand_counts[Latias_ex]
                         - discard_counts[Latias_ex]))

    kills = _kill_options(my_state, op_state, fairy_zone, latias_in_play)
    defender0 = op_state.active[0] if op_state.active and op_state.active[0] is not None else None
    act0 = my_state.active[0] if my_state.active else None
    bench_armed = any(p is not None
                      and _best_payable_dmg(p, my_state, op_state, defender0, fairy_zone) >= 100
                      for p in my_state.bench)
    act_dmg0 = _best_payable_dmg(act0, my_state, op_state, defender0, fairy_zone) if act0 is not None else 0
    # Fund the stuck active's retreat ONLY when one attach finishes the cost — measured bug:
    # a 3-retreat Kangaskhan soaked the {P} a dry bench Clefairy needed, "funding" a retreat
    # that never happened.
    fund_retreat = (act0 is not None and not latias_in_play and bench_armed and act_dmg0 < 60
                    and card_table[act0.id].retreatCost - len(act0.energies) == 1)

    energy_in_hand = sum(hand_counts[e] for e in ALL_ENERGY_IDS)
    patch_fixable = (hand_counts[Wondrous_Patch] > 0 and discard_counts[Psychic_Energy] > 0
                     and any(a == AreaType.BENCH and p.id in PSYCHIC_MON_IDS for a, _, p in mine))
    # Stalled = nothing armed and no route to a powered Rondo: no {P}/Telepath in hand, no
    # Crispin, no Patch line. (W/F in hand alone doesn't unstall — that's the Kangaskhan bank.)
    attack_stalled = (not bench_armed and act_dmg0 < 100 and hand_counts[Crispin] == 0
                      and not patch_fixable
                      and hand_counts[Psychic_Energy] + hand_counts[Telepath_Energy] == 0)
    controlled_draw = act0 is not None and act0.id == Mega_Kangaskhan_ex  # Run Errand draws exactly 2
    # Benching one more body is +20 Rondo: allowed while a slot stays reserved for Meowth/Fez
    # triggers and we aren't feeding their last prizes. (NOT gated on Area Zero being up —
    # a 5-bench still carries Rondo to 220, and an empty bench measured a 20-damage stall.)
    rondo_body_ok = (bench_room >= 2 and field_counts[Lillie_Clefairy_ex] > 0
                     and len(op_state.prize) > 2)
    benchable_in_hand = sum(1 for c in my_state.hand
                            if card_table[c.id].cardType == CardType.POKEMON)
    board_thin = (field_counts[Lillie_Clefairy_ex] + hand_counts[Lillie_Clefairy_ex] < 2
                  or field_counts[Latias_ex] + hand_counts[Latias_ex] < 1
                  or tera_count + hand_counts[Wellspring_Ogerpon_ex] + hand_counts[Koraidon_ex] < 1
                  or field_counts[Mega_Kangaskhan_ex] + hand_counts[Mega_Kangaskhan_ex] < 1)
    ogerpon_plan = field_counts[Wellspring_Ogerpon_ex] + hand_counts[Wellspring_Ogerpon_ex] > 0
    koraidon_plan = field_counts[Koraidon_ex] + hand_counts[Koraidon_ex] > 0
    koraidon_lever = opp_fighting_weak_wall and koraidon_plan
    moltres_plan = opp_ex_board and field_counts[Moltres] + hand_counts[Moltres] > 0

    # ---- per-hand-index usefulness (Ultra Ball cost, "dead hand" gates) ----------------------
    hand_usefulness = []
    seen = defaultdict(int)
    for c in my_state.hand:
        cid = c.id
        u = -10
        if cid == Lillie_Clefairy_ex:
            u = 200 if field_counts[cid] + seen[cid] < 2 else 40
        elif cid == Mega_Kangaskhan_ex:
            u = 100 if field_counts[cid] + seen[cid] < 1 and not opp_big_hitter else -20
        elif cid == Latias_ex:
            u = 180 if field_counts[cid] + seen[cid] < 1 else -30
        elif cid == Meowth_ex:
            u = 120 if not supporter_in_hand and field_counts[cid] + seen[cid] < 2 else -20
        elif cid == Fezandipiti_ex:
            u = 60 if seen[cid] == 0 and field_counts[cid] == 0 else -30
        elif cid == Wellspring_Ogerpon_ex or cid == Koraidon_ex:
            u = (140 if tera_count + seen[Wellspring_Ogerpon_ex] + seen[Koraidon_ex] < 2
                 else -25)
        elif cid == Moltres:
            u = 50 if opp_ex_board and field_counts[cid] == 0 else -20
        elif cid == Chien_Pao:
            u = 60 if opp_stadium_threat and field_counts[cid] == 0 else -20
        elif cid == Psychic_Energy:
            # With Wondrous Patch access a trashed {P} comes back onto a benched {P} mon:
            # pitching one to Ultra Ball is a feature, not a loss.
            patch_access = hand_counts[Wondrous_Patch] > 0 and any(
                a == AreaType.BENCH and p.id in PSYCHIC_MON_IDS for a, _, p in mine)
            u = 20 if patch_access and seen[cid] == 0 else (150 if clefairy_incomplete else 80)
        elif cid == Water_Energy:
            u = 80 if ogerpon_needs_water or hand_counts[Wellspring_Ogerpon_ex] > 0 else 25
        elif cid == Fighting_Energy:
            u = (120 if koraidon_lever else 80) if koraidon_needs_f or hand_counts[Koraidon_ex] > 0 else 25
        elif cid == Fire_Energy:
            u = 40 if moltres_plan else -5
        elif cid == Telepath_Energy:
            u = 140
        elif cid == Crispin:
            u = 150
        elif cid == Boss_Orders:
            u = 120
        elif cid == Cyrano:
            u = 80 if total_in_play < 5 else -10
        elif cid == Ciphermaniac:
            u = 15
        elif cid == Ultra_Ball:
            u = 80
        elif cid == Dusk_Ball:
            u = 70
        elif cid == Wondrous_Patch:
            u = 70 if discard_counts[Psychic_Energy] + hand_counts[Psychic_Energy] > 0 else 30
        elif cid == Prime_Catcher:
            u = 150  # the one ACE SPEC: never pitch it
        elif cid == Lillie_Pearl:
            u = 60 if seen[cid] == 0 else 10
        elif cid == Area_Zero_Underdepths:
            u = 40 if stadium_id != Area_Zero_Underdepths and seen[cid] == 0 else -50
        hand_usefulness.append(u)
        seen[cid] += 1
    useful_hand = sum(1 for u in hand_usefulness if u > 0)

    ctx = {
        "state": state, "my_state": my_state, "op_state": op_state, "mine": mine,
        "field_counts": field_counts, "hand_counts": hand_counts,
        "discard_counts": discard_counts, "stadium_id": stadium_id,
        "latias_in_play": latias_in_play, "tera_count": tera_count,
        "tera_in_play": tera_in_play, "benched_count": benched_count,
        "bench_room": bench_room, "total_in_play": total_in_play,
        "supporter_in_hand": supporter_in_hand, "opp_has_dragon": opp_has_dragon,
        "opp_ex_board": opp_ex_board, "opp_big_hitter": opp_big_hitter,
        "fairy_zone": fairy_zone, "opp_stadium_threat": opp_stadium_threat,
        "deck_energy_by_id": deck_energy_by_id, "deck_energy_left": deck_energy_left,
        "clefairy_powered": clefairy_powered, "clefairy_needs_p": clefairy_needs_p,
        "clefairy_incomplete": clefairy_incomplete,
        "ogerpon_needs_water": ogerpon_needs_water, "koraidon_needs_f": koraidon_needs_f,
        "p_bricked": p_bricked, "deck_p_mons": deck_p_mons, "kills": kills,
        "hand_usefulness": hand_usefulness, "useful_hand": useful_hand,
        "bench_armed": bench_armed, "fund_retreat": fund_retreat,
        "attack_stalled": attack_stalled, "controlled_draw": controlled_draw,
        "rondo_body_ok": rondo_body_ok, "benchable_in_hand": benchable_in_hand,
        "board_thin": board_thin, "ogerpon_plan": ogerpon_plan,
        "koraidon_plan": koraidon_plan, "moltres_plan": moltres_plan,
        "koraidon_lever": koraidon_lever, "clefairy_powered": clefairy_powered,
    }

    # ==========================================================================================
    # Context-specific selects with their own semantics
    # ==========================================================================================

    if context == SelectContext.IS_FIRST:
        # The guide says go SECOND (Crispin + attack on our first turn), but the measured field
        # says otherwise: every strong local agent elects first and wins 10-30 points more on
        # the play, and our go-first A/B trended positive (lucario 40->54, iono 20->25, n=40).
        # Documented guide-vs-measurement inconsistency; the field wins. CLEFAIRY_GO_FIRST=0
        # restores the guide's choice for A/Bs.
        want_first = os.environ.get("CLEFAIRY_GO_FIRST", "1") == "1"
        pick_type = OptionType.YES if want_first else OptionType.NO
        scores = [1 if o.type == pick_type else 0 for o in select.option]
        return _finish(scores, select)

    if context == SelectContext.ACTIVATE:
        # "Would you like to activate the effect?" — keyed on the card asking.
        ctx_card = select.contextCard
        cid = ctx_card.id if ctx_card is not None else eff_id
        yes = True
        if cid == Chien_Pao:
            # Snow Sink discards ANY stadium, including our own Area Zero: only nuke theirs.
            yes = opp_stadium_threat
        elif cid == Wellspring_Ogerpon_ex:
            # Torrential Pump's extra: shuffle 3 of its energy for 120 to the bench.
            # Only worth it when that converts a bench KO.
            yes = any(p is not None and p.hp <= 120 for p in op_state.bench)
        scores = [1 if ((o.type == OptionType.YES) == yes) else 0 for o in select.option]
        return _finish(scores, select)

    if context == SelectContext.DAMAGE:
        # Effect-damage target pick (Cruel Arrow 100 anywhere / Torrential Pump 120 to bench):
        # take the KO worth the most prizes, else soften the highest-value piece.
        dmg = 120 if eff_id == Wellspring_Ogerpon_ex else 100
        scores = []
        for o in select.option:
            pi = o.playerIndex if o.playerIndex is not None else 1 - my_index
            p = get_card(obs, o.area, o.index, pi)
            s = 0
            if p is not None and isinstance(p, Pokemon):
                if pi == my_index:
                    s = -1000
                else:
                    pr = prize_count(p)
                    if p.hp <= dmg:
                        s = 100000 if pr >= len(my_state.prize) else 10000 + pr * 1000 - p.hp
                    else:
                        s = pr * 300 - (p.hp - dmg) // 10
            scores.append(s)
        return _finish(scores, select)

    if context == SelectContext.SETUP_ACTIVE_POKEMON:
        # Guide: ideal start is Kangaskhan Active (300HP wall + Run Errand draw), Clefairy
        # powering up behind it. Meowth stays in hand for its bench-play trigger.
        setup_active = {Mega_Kangaskhan_ex: 100, Lillie_Clefairy_ex: 80, Latias_ex: 60,
                        Wellspring_Ogerpon_ex: 50, Koraidon_ex: 45, Fezandipiti_ex: 35,
                        Moltres: 25, Chien_Pao: 20, Meowth_ex: 10}
        scores = []
        for o in select.option:
            c = get_card(obs, o.area, o.index, my_index)
            scores.append(setup_active.get(c.id, 0) if c is not None else 0)
        return _finish(scores, select)

    if context == SelectContext.SETUP_BENCH_POKEMON:
        # Bench the engine pieces; hold Meowth and Chien-Pao (their triggers only fire on an
        # in-game bench play from hand). Engine loops one slot at a time.
        seen_bench = defaultdict(int)
        for _, _, p in mine:
            seen_bench[p.id] += 1
        scores = []
        for o in select.option:
            c = get_card(obs, o.area, o.index, my_index)
            s = -1
            if c is not None:
                cid = c.id
                if cid == Latias_ex:
                    s = 90 if seen_bench[cid] < 1 else 30
                elif cid == Lillie_Clefairy_ex:
                    s = 85 if seen_bench[cid] < 2 else 40
                elif cid == Wellspring_Ogerpon_ex:
                    s = 70 if seen_bench[cid] < 1 else 25
                elif cid == Koraidon_ex:
                    s = 40 if seen_bench[Wellspring_Ogerpon_ex] + seen_bench[cid] < 1 else 20
                elif cid == Mega_Kangaskhan_ex:
                    s = 15 if seen_bench[cid] < 1 else -1
                elif cid == Fezandipiti_ex:
                    s = 10 if seen_bench[cid] < 1 else -1
            scores.append(s)
        return _finish(scores, select, want=sum(1 for s in scores if s > 0))

    if context in (SelectContext.SWITCH, SelectContext.TO_ACTIVE):
        scores = []
        for o in select.option:
            p = get_card(obs, o.area, o.index, o.playerIndex if o.playerIndex is not None else my_index)
            s = 0
            if p is None:
                scores.append(s)
                continue
            if o.playerIndex is not None and o.playerIndex != my_index:
                # Gust pick (Boss's Orders / Prime Catcher): drag up what we can KO, else the
                # weakest high-value piece (the guide: vulnerable 2-prize support).
                if any(_best_payable_dmg(q, my_state, op_state, p, fairy_zone, opp_bench_delta=-1)
                       >= p.hp + _damage_shield(p)
                       for q in _reachable_attackers(my_state, latias_in_play)):
                    s = 100000 + prize_count(p) * 1000
                    if prize_count(p) >= len(my_state.prize):
                        s += 50000
                    # Equal-prize tiebreak: prefer the energized engine piece (a fueled Kyogre
                    # is Hammer-lanche's only recycler; killing it converts their self-mill
                    # into our deck-out wins) over an empty same-prize body.
                    s += 200 * len(p.energies) + p.hp // 10
                else:
                    s = prize_count(p) * 1000 + 150 * len(p.energies) - p.hp
            else:
                # Promoting my own next active.
                cid = p.id
                op_act = op_state.active[0] if op_state.active and op_state.active[0] is not None else None
                if cid == Lillie_Clefairy_ex:
                    powered = len(p.energies) >= 2 and EnergyType.PSYCHIC in p.energies
                    # A dry Clefairy promoted into an OHKO deck is a 2-prize gift — sacrifice
                    # 1-prize bodies first (the -300/prize OHKO penalty below does the sorting).
                    s = 1000 if powered else (450 if EnergyType.PSYCHIC in p.energies else 220)
                elif cid == Mega_Kangaskhan_ex:
                    s = 300 + (200 if latias_in_play else 0)
                    if len(op_state.prize) <= 3:
                        s -= 400  # a Kangaskhan KO would hand over the last 3 prizes
                    if opp_big_hitter:
                        s -= 250  # 2HKO'd for free by 150+ base hitters
                elif cid == Latias_ex:
                    s = 250
                elif cid in TERA_IDS:
                    s = 220 + 10 * len(p.energies)
                elif cid == Fezandipiti_ex:
                    s = 150
                elif cid in ONE_PRIZE_IDS:
                    # 1-prize speed bumps: promote them late so ex trades stop paying.
                    s = 130 + (300 if len(op_state.prize) <= 2 else 0)
                elif cid == Meowth_ex:
                    s = 100
                # An armed promotee that KOs the defender outranks every utility promotion.
                if (op_act is not None
                        and _best_payable_dmg(p, my_state, op_state, op_act, fairy_zone)
                        >= op_act.hp + _damage_shield(op_act)):
                    s += 800
                if _opp_can_ohko(op_state, p.hp):
                    # The promotee likely dies on their next turn: weigh the prizes it feeds.
                    s -= 300 * prize_count(p)
            scores.append(s)
        return _finish(scores, select)

    if context == SelectContext.TO_HAND:
        scores = []
        for o in select.option:
            c = get_card(obs, o.area, o.index, my_index)
            s = 0
            if c is not None:
                s = _search_pick_score(c.id, eff_id, ctx)
                if card_table[c.id].cardType != CardType.BASIC_ENERGY:
                    s -= 100 * hand_counts[c.id]  # diversify Pokémon/trainer picks
            scores.append(s)
        return _finish(scores, select)

    if context == SelectContext.TO_BENCH:
        # Deck->bench effects (Telepath Psychic Energy's rider benches up to 2 Basic {P}
        # Pokémon). Every body is +20 Rondo; prefer the attacker line.
        scores = []
        for o in select.option:
            c = get_card(obs, o.area, o.index, my_index)
            s = 10
            if c is not None:
                if c.id == Lillie_Clefairy_ex:
                    s = 100
                elif c.id == Latias_ex:
                    s = 90 if field_counts[Latias_ex] == 0 else 60
                elif c.id == Mega_Kangaskhan_ex:
                    s = 40 if not opp_big_hitter else 5
                else:
                    s = 50
            scores.append(s)
        return _finish(scores, select)

    if context == SelectContext.TO_DECK and eff_id == Ciphermaniac:
        # Ciphermaniac's Codebreaking: stack the two cards that fix the current blocker on top.
        # Only played when a controlled draw (Run Errand's exactly-2) lifts them this turn.
        scores = []
        for o in select.option:
            c = get_card(obs, o.area, o.index, my_index)
            s = 1
            if c is not None:
                cid = c.id
                if cid in (Psychic_Energy, Telepath_Energy) and clefairy_incomplete:
                    s = 300
                elif cid == Lillie_Clefairy_ex and field_counts[cid] + hand_counts[cid] == 0:
                    s = 280
                elif cid == Boss_Orders and kills["gust_worth"]:
                    s = 260
                elif cid == Crispin:
                    s = 240
                elif cid == Wondrous_Patch and discard_counts[Psychic_Energy] > 0:
                    s = 220
                elif cid in ENERGY_IDS:
                    s = 150
                elif cid == Area_Zero_Underdepths and stadium_id != Area_Zero_Underdepths and tera_in_play:
                    s = 140
            scores.append(s)
        return _finish(scores, select)

    if context == SelectContext.ATTACH_TO:
        # Picking WHICH energy card gets attached (Crispin's attach half, Wondrous Patch's
        # trash pick — the Patch is always {P}).
        scores = []
        for o in select.option:
            c = get_card(obs, o.area, o.index, my_index)
            s = 1
            if c is not None and c.id in card_table:
                et = card_table[c.id].energyType
                if (et == EnergyType.FIGHTING and koraidon_needs_f and koraidon_lever
                        and clefairy_powered):
                    s = 320  # weakness-lever: the attach half arms Koraidon over topping Clefairy
                elif et == EnergyType.PSYCHIC and clefairy_needs_p:
                    s = 300
                elif et == EnergyType.WATER and ogerpon_needs_water:
                    s = 220
                elif et == EnergyType.FIGHTING and koraidon_needs_f:
                    s = 210
                elif et == EnergyType.PSYCHIC:
                    s = 200
                elif et == EnergyType.FIRE and moltres_plan:
                    s = 150
                else:
                    s = 100
            scores.append(s)
        pick = _finish(scores, select)
        if pick:
            c = get_card(obs, select.option[pick[0]].area, select.option[pick[0]].index, my_index)
            if c is not None and c.id in card_table:
                pending_attach_type = card_table[c.id].energyType
        return pick

    if context == SelectContext.ATTACH_FROM:
        # Picking WHICH of my Pokémon receives an energy (Crispin's attach half, Wondrous
        # Patch's benched-{P} target).
        et = pending_attach_type
        if eff_id in ALL_ENERGY_IDS:
            et = card_table[eff_id].energyType  # manual attach: the effect IS the energy card
        elif eff_id == Wondrous_Patch:
            et = EnergyType.PSYCHIC
        scores = []
        for o in select.option:
            p = get_card(obs, o.area, o.index, my_index)
            s = 0
            if p is not None:
                if fund_retreat and o.area == AreaType.ACTIVE:
                    s = 1150  # pay the stuck active's retreat so the armed bench can promote
                else:
                    s = _energy_target_score(p, et, ctx)
            scores.append(s)
        return _finish(scores, select)

    if context == SelectContext.DISCARD:
        own_hand = [o for o in select.option
                    if o.area == AreaType.HAND and (o.playerIndex is None or o.playerIndex == my_index)]
        if own_hand:
            # Ultra Ball's cost (and any other hand discard): pitch the least useful cards.
            scores = []
            for o in select.option:
                if o.area == AreaType.HAND and o.index < len(hand_usefulness):
                    scores.append(-hand_usefulness[o.index])
                else:
                    scores.append(0)
            return _finish(scores, select)
        # Bench shrink (Area Zero leaving / last Tera gone): dump spent utility bodies, keep
        # the attackers, the draw engine, and above all a Tera (or the shrink cascades).
        scores = []
        for o in select.option:
            p = get_card(obs, o.area, o.index, my_index)
            s = 0
            if p is not None and isinstance(p, Pokemon):
                base = {Meowth_ex: 1000, Moltres: 850, Chien_Pao: 820, Fezandipiti_ex: 750,
                        Mega_Kangaskhan_ex: 500, Lillie_Clefairy_ex: 350, Koraidon_ex: 250,
                        Wellspring_Ogerpon_ex: 240, Latias_ex: 150}.get(p.id, 400)
                if p.id in TERA_IDS and tera_count <= 1:
                    base = 10  # the LAST Tera: losing it forces the shrink all over again
                if p.id in ONE_PRIZE_IDS and len(op_state.prize) <= 2:
                    base = 200  # late game the 1-prize wall is the plan
                if p.id == Mega_Kangaskhan_ex and field_counts[Mega_Kangaskhan_ex] <= 1:
                    base = 120  # the only repeatable draw
                if p.id == Lillie_Clefairy_ex and len(p.energies) >= 2:
                    base = 60
                s = base - 300 * len(p.energies)
                if field_counts[p.id] > 1:
                    s += 200
            scores.append(s)
        return _finish(scores, select)

    if context == SelectContext.DISCARD_ENERGY:
        # Retreat cost (usually free via Skyliner): burn {R} first, keep {P}/Telepath last.
        scores = []
        for o in select.option:
            et = None
            if o.energyIndex is not None:
                act = my_state.active[0] if my_state.active else None
                if act is not None and o.energyIndex < len(act.energies):
                    et = act.energies[o.energyIndex]
            scores.append({EnergyType.FIRE: 5, EnergyType.WATER: 3, EnergyType.FIGHTING: 3,
                           EnergyType.PSYCHIC: 1}.get(et, 4))
        return _finish(scores, select)

    if context == SelectContext.DISCARD_ENERGY_CARD:
        # Enemy-forced energy discard (none of our own cards use this select): give up {R}
        # first, the Telepath and {P} Rondo fuel last.
        scores = []
        for o in select.option:
            host = get_card(obs, o.area, o.index, my_index)
            eid = 0
            if (host is not None and o.energyIndex is not None
                    and o.energyIndex < len(host.energyCards)):
                eid = host.energyCards[o.energyIndex].id
            scores.append({Fire_Energy: 5, Water_Energy: 3, Fighting_Energy: 3,
                           Psychic_Energy: 1, Telepath_Energy: 0}.get(eid, 4))
        return _finish(scores, select)

    if context in (SelectContext.TO_DECK_ENERGY, SelectContext.TO_HAND_ENERGY):
        # Torrential Pump's shuffle-3 / Icicle Loop's bounce: keep the scarce {W} attached
        # when there's a choice.
        scores = []
        for o in select.option:
            et = None
            if o.energyIndex is not None:
                act = my_state.active[0] if my_state.active else None
                if act is not None and o.energyIndex < len(act.energies):
                    et = act.energies[o.energyIndex]
            scores.append(1 if et == EnergyType.WATER else 2)
        return _finish(scores, select)

    # ==========================================================================================
    # MAIN (and any remaining context): score-and-sort over the generic option types
    # ==========================================================================================

    scores = []
    for o in select.option:
        score = 0
        if o.type == OptionType.NUMBER:
            score = o.number
        elif o.type == OptionType.YES:
            score = 1
        elif o.type == OptionType.PLAY:
            c = get_card(obs, AreaType.HAND, o.index, my_index)
            score = _play_score(c, ctx)
        elif o.type == OptionType.ATTACH:
            # Manual attach arrives as one option per (hand card x target Pokémon): the hand
            # card sits at (area=HAND, index), the target at (inPlayArea, inPlayIndex). Tools
            # (Lillie's Pearl) share this shape — branch on the card BEFORE reading energyType.
            ecard = get_card(obs, o.area, o.index, my_index)
            target = get_card(obs, o.inPlayArea, o.inPlayIndex, my_index)
            score = -1
            if ecard is not None and target is not None:
                if ecard.id == Lillie_Pearl:
                    # Only a Lillie's Pokémon profits (prize reduction): Clefairy only here.
                    if target.id == Lillie_Clefairy_ex and not target.tools:
                        score = 8760 if len(target.energies) >= 1 else 8720
                    else:
                        score = -1
                elif ecard.id in ALL_ENERGY_IDS:
                    et = card_table[ecard.id].energyType
                    s = _energy_target_score(target, et, ctx)
                    if (ecard.id == Telepath_Energy and target.id in PSYCHIC_MON_IDS
                            and deck_p_mons > 0 and bench_room >= 1):
                        s += 120  # the rider benches up to 2 {P} basics: free Rondo bodies
                    if fund_retreat and o.inPlayArea == AreaType.ACTIVE:
                        s = 1150
                    score = 8000 + s
        elif o.type == OptionType.ABILITY:
            p = get_card(obs, o.area, o.index, my_index)
            score = -1
            if p is not None:
                if p.id == Fezandipiti_ex:
                    score = 58000 if my_state.deckCount > 3 else -1
                elif p.id == Mega_Kangaskhan_ex:
                    score = 57000 if my_state.deckCount > 2 else -1
                else:
                    score = 50000  # any other offered ability: use it
        elif o.type == OptionType.RETREAT:
            score = _retreat_score(my_state, op_state, fairy_zone, latias_in_play)
        elif o.type == OptionType.ATTACK:
            score = _attack_score(o.attackId, my_state, op_state, fairy_zone)
        elif o.type == OptionType.EVOLVE:
            score = 110000  # no evolutions in this deck; harmless default
        elif o.type == OptionType.END:
            score = 0
        scores.append(score)

    return _finish(scores, select)


def _search_pick_score(cid: int, eff_id: int, ctx: dict) -> int:
    """TO_HAND picks: deck/discard/looking searches, branched on the activating card."""
    data = card_table.get(cid)
    et = data.energyType if data is not None else None
    field_counts = ctx["field_counts"]
    hand_counts = ctx["hand_counts"]
    if eff_id == Crispin:
        # This pick goes to HAND; the attach pick follows and must be a DIFFERENT type. Leave
        # the type we want ATTACHED scored low here so the attach half gets it.
        if ctx["clefairy_needs_p"]:
            if et == EnergyType.PSYCHIC:
                return 60  # leave {P} for the attach half
            if et == EnergyType.FIGHTING and ctx["koraidon_lever"]:
                return 330  # weakness-lever: make sure {F} is in the fetched pair
            if et == EnergyType.WATER and ctx["ogerpon_plan"]:
                return 300
            if et == EnergyType.FIGHTING and ctx["koraidon_plan"]:
                return 280
            if et == EnergyType.FIRE and ctx["moltres_plan"]:
                return 200
            return 150
        # No {P} hole to fill: bank {P} in hand for the next Clefairy, attach the situational.
        if et == EnergyType.PSYCHIC:
            return 250
        if et == EnergyType.WATER and ctx["ogerpon_plan"]:
            return 120
        if et == EnergyType.FIGHTING and ctx["koraidon_plan"]:
            return 110
        return 80
    if eff_id == Meowth_ex:
        # Last-Ditch Catch: fetch the Supporter this turn needs.
        no_attacker = field_counts[Lillie_Clefairy_ex] + hand_counts[Lillie_Clefairy_ex] == 0
        if cid == Cyrano and no_attacker:
            return 310
        if cid == Crispin and (ctx["clefairy_incomplete"]
                               or sum(hand_counts[e] for e in ALL_ENERGY_IDS) == 0):
            return 300
        if cid == Boss_Orders and ctx["kills"]["gust_worth"]:
            return 290
        if cid == Cyrano and ctx["board_thin"]:
            return 240
        if cid == Crispin:
            return 230
        if cid == Boss_Orders:
            return 100
        if cid == Ciphermaniac:
            return 60
        return 50
    if eff_id == Cyrano:
        # Up to 3 Pokémon ex (Mega Kangaskhan IS offered — confirmed in reference traces).
        if cid == Lillie_Clefairy_ex:
            tot = field_counts[cid] + hand_counts[cid]
            return 300 if tot < 1 else (280 if tot < 2 else 60)
        if cid in TERA_IDS:
            if cid == Koraidon_ex and ctx["koraidon_lever"] and field_counts[cid] + hand_counts[cid] < 1:
                return 285  # weakness-lever: the OHKO attacker outranks the 2nd Clefairy (280)
            if ctx["tera_count"] + hand_counts[Wellspring_Ogerpon_ex] + hand_counts[Koraidon_ex] < 1:
                return 270 if cid == Wellspring_Ogerpon_ex else 250
            if ctx["tera_count"] == 1 and ctx["benched_count"] >= 5:
                return 120  # second Tera = 8-bench insurance
            return 35
        if cid == Latias_ex:
            return 260 if field_counts[cid] + hand_counts[cid] < 1 else 40
        if cid == Mega_Kangaskhan_ex:
            return (255 if field_counts[cid] + hand_counts[cid] < 1
                    and not ctx["opp_big_hitter"] else 45)
        if cid == Meowth_ex:
            return 200 if not ctx["supporter_in_hand"] and field_counts[cid] == 0 else 40
        if cid == Fezandipiti_ex:
            return 150 if field_counts[cid] + hand_counts[cid] < 1 else 30
        return 30
    # Dusk Ball (bottom-7 look) / Ultra Ball / any generic Pokémon search: fill the board.
    if cid == Lillie_Clefairy_ex:
        if field_counts[cid] == 0:
            return 320
        if field_counts[cid] + hand_counts[cid] < 2:
            return 290
        return 60
    if cid == Latias_ex:
        return 260 if field_counts[cid] + hand_counts[cid] < 1 else 40
    if cid in TERA_IDS:
        if cid == Koraidon_ex and ctx["koraidon_lever"] and field_counts[cid] + hand_counts[cid] < 1:
            return 310  # weakness-lever: the OHKO attacker outranks the 2nd Clefairy (290)
        if ctx["tera_count"] + hand_counts[Wellspring_Ogerpon_ex] + hand_counts[Koraidon_ex] < 1:
            return 300 if cid == Wellspring_Ogerpon_ex else 270
        if ctx["tera_count"] == 1 and ctx["benched_count"] >= 5:
            return 120
        return 35
    if cid == Mega_Kangaskhan_ex:
        return (210 if field_counts[cid] + hand_counts[cid] < 1
                and not ctx["opp_big_hitter"] else 45)
    if cid == Meowth_ex:
        return (240 if not ctx["supporter_in_hand"] and field_counts[cid] == 0
                and not ctx["state"].supporterPlayed else 40)
    if cid == Fezandipiti_ex:
        return 60 if field_counts[cid] + hand_counts[cid] < 1 else 20
    if cid == Chien_Pao:
        return 90 if ctx["opp_stadium_threat"] and field_counts[cid] == 0 else 20
    if cid == Moltres:
        return 80 if ctx["opp_ex_board"] and field_counts[cid] == 0 else 20
    return 25  # any body is +20 Rondo


def _play_score(c, ctx: dict) -> int:
    """MAIN-phase PLAY option: the score band encodes within-turn ordering (abilities fire in
    the 50000s, supporters in the 20000s, attach in the 8000s, attacks close the turn)."""
    if c is None:
        return 0
    data = card_table[c.id]
    cid = c.id
    my_state = ctx["my_state"]
    op_state = ctx["op_state"]
    field_counts = ctx["field_counts"]
    hand_counts = ctx["hand_counts"]
    bench_room = ctx["bench_room"]
    kills = ctx["kills"]

    if data.cardType == CardType.POKEMON:
        # Bench-out safety valve: never be left with a lone active.
        if ctx["total_in_play"] <= 1:
            pref = {Lillie_Clefairy_ex: 0, Mega_Kangaskhan_ex: 1, Latias_ex: 2,
                    Wellspring_Ogerpon_ex: 3, Meowth_ex: 4, Fezandipiti_ex: 5, Koraidon_ex: 6,
                    Chien_Pao: 7, Moltres: 8}.get(cid, 10)
            return 200000 - pref
        if cid == Lillie_Clefairy_ex:
            if field_counts[cid] < 2:
                return 99800
            return 17500 if ctx["rondo_body_ok"] else -1  # extras: bodies + backup attackers
        if cid == Latias_ex:
            if field_counts[cid] < 1:
                return 99000
            return 17200 if ctx["rondo_body_ok"] else -1
        if cid == Meowth_ex:
            # Its whole point is the on-play Supporter search: bench it when we lack one, or
            # lack CRISPIN specifically while a Clefairy is dry (Crispin is the engine).
            need_crispin = ctx["clefairy_incomplete"] and hand_counts[Crispin] == 0
            if (field_counts[cid] < 2 and not ctx["state"].supporterPlayed
                    and (not ctx["supporter_in_hand"] or need_crispin)):
                return 99000
            return 17000 if ctx["rondo_body_ok"] else -1
        if cid == Wellspring_Ogerpon_ex:
            if ctx["tera_count"] == 0:
                return 98500  # the Tera enabler lands BEFORE Area Zero (band ordering)
            if ctx["tera_count"] == 1 and ctx["benched_count"] >= 5:
                return 22500  # a second Tera keeps the 8-bench alive through a KO
            return 17100 if ctx["rondo_body_ok"] else -1
        if cid == Koraidon_ex:
            if ctx["tera_count"] == 0 and hand_counts[Wellspring_Ogerpon_ex] == 0:
                return 98400
            if ctx["tera_count"] == 1 and ctx["benched_count"] >= 5:
                return 22400
            f_reachable = (hand_counts[Fighting_Energy] > 0
                           or ctx["deck_energy_by_id"][Fighting_Energy] > 0)
            if (field_counts[cid] == 0 and f_reachable
                    and bench_room >= (1 if ctx["koraidon_lever"] else 2)):
                # Weakness-lever matchup: land the OHKO attacker ahead of Fez (20000).
                return 21800 if ctx["koraidon_lever"] else 19000
            return 16900 if ctx["rondo_body_ok"] else -1
        if cid == Chien_Pao:
            # Snow Sink counter-stadium (the ACTIVATE handler declines on our own Area Zero).
            if ctx["opp_stadium_threat"] and field_counts[cid] == 0:
                return 50000
            return 16800 if ctx["rondo_body_ok"] else -1
        if cid == Fezandipiti_ex:
            if ctx["state"].turn >= 3 and field_counts[cid] == 0 and bench_room >= 2:
                return 20000
            return 16700 if ctx["rondo_body_ok"] else -1
        if cid == Moltres:
            if ctx["opp_ex_board"] and field_counts[cid] == 0 and bench_room >= 2:
                return 18000
            return 16600 if ctx["rondo_body_ok"] else -1
        if cid == Mega_Kangaskhan_ex:
            # The only repeatable draw AND the {C}{C}{C} fallback attacker (4 copies): the first
            # body goes down even against big hitters — an empty bench measured worse (20-damage
            # Rondo stall, Kangaskhans dead in hand for 20 turns). The 3-prize liability gate
            # only holds back EXTRA copies and the last-prizes endgame.
            if field_counts[cid] == 0 and len(op_state.prize) >= 4 and bench_room >= 1:
                return 21000
            return 16500 if (ctx["rondo_body_ok"] and not ctx["opp_big_hitter"]
                             and len(op_state.prize) >= 4) else -1
        return -1

    if data.cardType == CardType.BASIC_ENERGY or cid in ALL_ENERGY_IDS:
        # Manual attach offered as PLAY in some engine paths: keep parity with the ATTACH band.
        et = data.energyType
        best = 0
        for _, _, p in ctx["mine"]:
            best = max(best, _energy_target_score(p, et, ctx))
        return 8000 + best

    if data.cardType == CardType.SUPPORTER:
        if cid == Boss_Orders:
            if kills["gust_worth"] and kills["bench_wins"]:
                return 130000  # gust for game
            return 27000 if kills["gust_worth"] else -1
        if cid == Crispin:
            if ctx["deck_energy_left"] <= 0:
                return -1
            return 26000 if (ctx["clefairy_incomplete"] or ctx["ogerpon_needs_water"]
                             or ctx["koraidon_needs_f"]) else 24000
        if cid == Cyrano:
            if field_counts[Lillie_Clefairy_ex] + hand_counts[Lillie_Clefairy_ex] == 0:
                return 26500  # no attacker anywhere: finding Clefairy outranks the energy
            return 25000 if ctx["board_thin"] else -1
        if cid == Ciphermaniac:
            # Narrow stall-breaker: a stall means we aren't searching either, so the stacked
            # {P}s survive to the next draws even without Run Errand's controlled 2.
            return 15000 if ctx["attack_stalled"] else -1
        return -1

    if data.cardType == CardType.STADIUM:
        if cid == Area_Zero_Underdepths and ctx["stadium_id"] != Area_Zero_Underdepths:
            if ctx["tera_in_play"]:
                if bench_room == 0 and ctx["benchable_in_hand"] > 0:
                    return 110000  # unlock the bench BEFORE this turn's Pokémon plays
                if ctx["benched_count"] >= 3 or ctx["opp_stadium_threat"]:
                    return 30000
                return 14000
            if ctx["opp_stadium_threat"]:
                return 28000  # bounce their stadium even without a Tera
        return -1

    # Items
    if cid == Ultra_Ball:
        if field_counts[Lillie_Clefairy_ex] + hand_counts[Lillie_Clefairy_ex] == 0:
            return 46000  # no attacker anywhere: pay any 2 cards to find one
        # "Expendable" counts genuinely cheap cards (<=30, e.g. spare stadiums, Ciphermaniac);
        # the strict <=0 count measured Ultra Ball never firing through a 7-turn brick.
        expendable = sum(1 for u in ctx["hand_usefulness"] if u <= 30) - 1
        return 45000 if expendable >= 2 and ctx["board_thin"] else -1
    if cid == Dusk_Ball:
        # Costless bottom-7 look: a found body is +20 Rondo, a miss shuffles. Near-unconditional.
        return 44000 if my_state.deckCount > 0 else -1
    if cid == Wondrous_Patch:
        # Free extra attach from the trash (the engine gates on {P} in trash + benched {P} mon):
        # arming a benched Clefairy a turn early is the whole point.
        incomplete_benched = any(
            a == AreaType.BENCH and p.id == Lillie_Clefairy_ex
            and (EnergyType.PSYCHIC not in p.energies or len(p.energies) < 2)
            for a, _, p in ctx["mine"])
        if ctx["discard_counts"][Psychic_Energy] > 0:
            if incomplete_benched:
                return 61000
            if any(a == AreaType.BENCH and p.id in PSYCHIC_MON_IDS and len(p.energies) < 3
                   for a, _, p in ctx["mine"]):
                return 43000
        return -1
    if cid == Prime_Catcher:
        # The one ACE SPEC: gust + mandatory self-switch. Save it for a conversion Boss can't
        # do this turn (no Boss in hand) with an armed bench attacker to switch in.
        if kills["gust_worth"] and ctx["bench_armed"] and hand_counts[Boss_Orders] == 0:
            return 129000 if kills["bench_wins"] else 23000
        return -1
    return -1


def _retreat_score(my_state, op_state, fairy_zone: bool, latias_in_play: bool) -> int:
    """Retreat when a bench attacker beats the active's output. The engine only offers RETREAT
    when the cost is payable; with Skyliner up every Basic retreats free, so the Kangaskhan
    draw-rotation (Run Errand -> free retreat -> armed Clefairy) is this list's core loop."""
    act = my_state.active[0] if my_state.active else None
    if act is None:
        return -1
    defender = op_state.active[0] if op_state.active and op_state.active[0] is not None else None
    free = latias_in_play or card_table[act.id].retreatCost == 0
    cheap = card_table[act.id].retreatCost <= 1
    act_dmg = _best_payable_dmg(act, my_state, op_state, defender, fairy_zone)
    if defender is not None and act_dmg >= defender.hp + _damage_shield(defender):
        return -1  # the active already converts the KO: stay and attack
    bench_best = 0
    bench_lethal = False
    for p in my_state.bench:
        if p is None:
            continue
        d = _best_payable_dmg(p, my_state, op_state, defender, fairy_zone)
        bench_best = max(bench_best, d)
        if defender is not None and d >= defender.hp + _damage_shield(defender):
            bench_lethal = True
    if bench_lethal:
        return 12000 if (free or cheap) else 11000  # enabling the KO pays for the energy burn
    if bench_best > act_dmg + 40:
        # A meaningfully better attacker waits on the bench: pivot for free, or cheaply when
        # the active contributes nothing anyway.
        return 10800 if free else (10000 if cheap and act_dmg == 0 else -1)
    # Nothing better armed: rotate the draw engine through the Active Spot (Run Errand is
    # Active-only). Deck guard against rotating ourselves into a deck-out.
    if (free and act.id != Mega_Kangaskhan_ex and act_dmg == 0 and my_state.deckCount > 8
            and any(p is not None and p.id == Mega_Kangaskhan_ex for p in my_state.bench)):
        return 9800
    return -1


def _attack_score(attack_id: int, my_state, op_state, fairy_zone: bool) -> int:
    """Attacks close the turn: lethal > utility > chip, and chip is ordered by real damage so
    a big Rondo outranks Rapid-Fire and vice versa. Attacking is free — never pass it up."""
    defender = op_state.active[0] if op_state.active and op_state.active[0] is not None else None
    my_act = my_state.active[0] if my_state.active else None
    my_need = len(my_state.prize)
    # KOing their ACTIVE with an empty bench ends the game (bench-out) no matter the prizes —
    # our single biggest win mode vs the wall decks, previously invisible to the lethal bands.
    opp_bench_empty = not any(p is not None for p in op_state.bench)
    if attack_id == ATK_CRUEL_ARROW:
        # 100 to ANY opponent Pokémon: check the whole board, not just the defender.
        targets = [p for p in ([defender] if defender is not None else []) + list(op_state.bench)
                   if p is not None]
        kill_ts = [p for p in targets if p.hp <= 100]
        if kill_ts:
            best_pr = max(prize_count(p) for p in kill_ts)
            if best_pr >= my_need:
                return 140000
            if opp_bench_empty and defender is not None and defender.hp <= 100:
                return 140000
            return 2300
        return 700
    dmg = _attack_damage(attack_id, my_state, op_state, defender, fairy_zone, my_act)
    if defender is not None and dmg >= defender.hp + _damage_shield(defender):
        if prize_count(defender) >= my_need or opp_bench_empty:
            return 140000
        base = {ATK_RONDO: 2550, ATK_PUMP: 2500, ATK_ORICHALCUM: 2450, ATK_RAPID_FIRE: 2400,
                ATK_FIGHTING_WINGS: 2380, ATK_ICICLE_LOOP: 2200, ATK_SOB: 2100,
                ATK_TUCK_TAIL: 2000}.get(attack_id, 2000)
        if attack_id in (ATK_EON_BLADE, ATK_IMPACT_BLOW):
            # KO at the cost of next turn's attack: fine for a real prize haul.
            base = 2350 if prize_count(defender) >= 2 else 1200
        if (my_act is not None and my_act.id in ONE_PRIZE_IDS
                and prize_count(defender) >= 2):
            base += 500  # a 1-prize body KOs a multi-prize ex: the trade we want
        return base
    # No KO: chip ordered by real damage output; attacks are free, so anything beats END.
    if attack_id == ATK_EON_BLADE:
        # Tank softener: into a 250+HP wall Rondo can't OHKO, a flat 200 races better than a
        # thin-bench Rondo, and Skyliner makes the post-lock retreat free anyway.
        if (defender is not None and prize_count(defender) >= 2
                and defender.hp + _damage_shield(defender) > 250):
            return 1300
        return 300  # otherwise: 200 + skipping next turn is a last resort
    if attack_id == ATK_IMPACT_BLOW:
        return 500 + dmg
    if attack_id == ATK_PUMP:
        bench_kill = any(p is not None and p.hp <= 120 for p in op_state.bench)
        if bench_kill:
            return 2350  # the bench snipe converts even without an active KO
    return 600 + dmg * 4


