# As of **July 11, 2026**, Standard permits cards with **H, I, and J regulation marks**. My pick for a strong but relatively accessible deck is James Kowalski’s **Lillie’s Clefairy ex / Mega Kangaskhan ex**, which won the Masters division of **NAIC 2026**. The same list also finished 23rd and 70th at NAIC, while the archetype recently made 5th at Turin and 23rd at Indianapolis. ([Pokémon Forums][1])

