def get_card(obs: Observation, area: AreaType, index: int, player_index: int) -> Pokemon | Card | None:
    """Helper function to safely extract a Card or Pokemon object from specific zones."""
    ps = obs.current.players[player_index]
    match area:
        case AreaType.DECK:
            return obs.select.deck[index]
        case AreaType.HAND:
            return ps.hand[index]
        case AreaType.DISCARD:
            return ps.discard[index]
        case AreaType.ACTIVE:
            return ps.active[index]
        case AreaType.BENCH:
            return ps.bench[index]
        case AreaType.PRIZE:
            return ps.prize[index]
        case AreaType.STADIUM:
            return obs.current.stadium[index]
        case AreaType.LOOKING:
            return obs.current.looking[index]
        case _:
            return None


def prize_count(pokemon: Pokemon) -> int:
    """Calculates how many Prize cards a Pokémon yields upon being Knocked Out, factoring in modifiers."""
    data = card_table[pokemon.id]
    count = 3 if data.megaEx else 2 if data.ex else 1
    for card in pokemon.energyCards:
        if card.id == 12:  # Legacy Energy
            count -= 1
    for card in pokemon.tools:
        if card.id == 1172 and "Lillie" in data.name:  # Lillie’s Pearl
            count -= 1
    return max(0, count)


def pokemon_score(pokemon: Pokemon) -> int:
    """Heuristically evaluates the tactical worth of targeting a specific Pokémon on the opponent's field."""
    data = card_table[pokemon.id]
    score = prize_count(pokemon) * 1000
    score += len(pokemon.energies) * 150
    score += len(pokemon.tools) * 100
    if data.stage2:
        score += 250
    elif data.stage1:
        score += 130
    score += pokemon.hp
    return score


def _my_pokemon(my_state) -> list[tuple[AreaType, int, Pokemon]]:
    out = []
    for i, p in enumerate(my_state.active):
        if p is not None:
            out.append((AreaType.ACTIVE, i, p))
    for i, p in enumerate(my_state.bench):
        if p is not None:
            out.append((AreaType.BENCH, i, p))
    return out


def _damage_shield(defender: Pokemon) -> int:
    """Worst-case flat damage reduction the defender may have up ("takes N less damage" attack
    riders, e.g. Mega Abomasnow's Frost Barrier). We can't see whether it was actually used last
    turn, so assume it when the attack is payable: one over-discard beats bouncing a 5-energy
    Bellowing off a 3-prize tank at 30hp (measured)."""
    best = 0
    for aid in card_table[defender.id].attacks:
        a = attack_table.get(aid)
        if a is None or len(defender.energies) < len(a.energies):
            continue
        m = re.search(r"takes (\d+) less damage", a.text or "")
        if m:
            best = max(best, int(m.group(1)))
    return best


def _k_needed(defender: Pokemon, fairy_zone: bool = False) -> int:
    """Energies Bellowing Thunder must discard to KO the defender (70 per card, weakness x2).
    Fairy Zone REWRITES an opposing Dragon's weakness to {P}, so it can only remove (never add)
    the Dragon weakness Bellowing would exploit."""
    data = card_table[defender.id]
    per = 70
    hp = defender.hp + _damage_shield(defender)
    if data.weakness == EnergyType.DRAGON and not (fairy_zone and data.energyType == EnergyType.DRAGON):
        per = 140
    elif data.resistance == EnergyType.DRAGON:
        hp += 30
    return max(1, ceil(hp / per))


def _weak_mult(defender: Pokemon, atk_type, fairy_zone: bool) -> tuple[int, int]:
    """(weakness multiplier, resistance subtraction) for an attack of `atk_type` into `defender`.
    The obs Pokemon has no live weakness field, so Fairy Zone's rewrite is applied here."""
    data = card_table[defender.id]
    weak = data.weakness
    if fairy_zone and data.energyType == EnergyType.DRAGON:
        weak = EnergyType.PSYCHIC
    mult = 2 if (weak is not None and atk_type is not None and weak == atk_type) else 1
    res = 30 if (data.resistance is not None and atk_type is not None
                 and data.resistance == atk_type) else 0
    return mult, res


def _attack_damage(attack_id: int, my_state, op_state, defender: Pokemon | None,
                   total_in_play: int, fairy_zone: bool, attacker: Pokemon | None = None) -> int:
    """Expected damage of a (non-Bellowing) attack into the current defender, weakness applied.
    Coin-flip attacks use their guaranteed base. Cruel Arrow / Pump bench hits are effect damage
    (no weakness) and get their own handling at the call sites."""
    if defender is None:
        return 0
    act = attacker if attacker is not None else (my_state.active[0] if my_state.active else None)
    base, atk_type = 0, None
    if attack_id == ATK_LEAF_SHOWER:
        n = (len(act.energies) if act is not None else 0) + len(defender.energies)
        base, atk_type = 30 + 30 * n, EnergyType.GRASS
    elif attack_id == ATK_SOB:
        base, atk_type = 20, EnergyType.WATER
    elif attack_id == ATK_PUMP:
        base, atk_type = 100, EnergyType.WATER
    elif attack_id == ATK_CRUEL_ARROW:
        return 100  # effect damage: no weakness/resistance
    elif attack_id == ATK_EON_BLADE:
        base, atk_type = 200, EnergyType.PSYCHIC
    elif attack_id == ATK_ICICLE_LOOP:
        base, atk_type = 120, EnergyType.WATER
    elif attack_id == ATK_RONDO:
        benched = (sum(1 for p in my_state.bench if p is not None)
                   + sum(1 for p in op_state.bench if p is not None))
        base, atk_type = 20 + 20 * benched, EnergyType.PSYCHIC
    elif attack_id == ATK_RAPID_FIRE:
        base, atk_type = 200, EnergyType.COLORLESS
    elif attack_id == ATK_COORDINATED:
        base, atk_type = 20 * total_in_play, EnergyType.FIGHTING  # every Pokémon here is a Basic
    elif attack_id == ATK_TUCK_TAIL:
        base, atk_type = 60, EnergyType.COLORLESS
    else:
        return 0
    mult, res = _weak_mult(defender, atk_type, fairy_zone)
    return max(0, base * mult - res)


def _opp_big_hitter(op_state) -> bool:
    """Cheap 2HKO pressure proxy: anything on their board with a >=150 BASE damage attack makes
    a benched 300HP/3-prize Kangaskhan a 2-hit gift (Phantom Dive decks). Variable attacks
    (base 0, e.g. Bellowing) don't trip this — killing a tank costs THEM real fuel."""
    return any(attack_table[aid].damage >= 150
               for p in list(op_state.active or []) + list(op_state.bench)
               if p is not None and p.id in card_table
               for aid in card_table[p.id].attacks if aid in attack_table)


def _opp_can_ohko(op_state, our_hp: int) -> bool:
    """Whether the opponent's active has a payable attack whose BASE damage one-shots `our_hp`.
    Base damage only (variable attacks underestimate) — a deliberate, cheap proxy."""
    act = op_state.active[0] if op_state.active and op_state.active[0] is not None else None
    if act is None or act.id not in card_table:
        return False
    for aid in card_table[act.id].attacks:
        a = attack_table.get(aid)
        if a is not None and a.damage >= our_hp and len(act.energies) >= len(a.energies):
            return True
    return False


def _board_fuel(my_state) -> int:
    """Total Basic Energy cards attached to my Pokémon (all energy in this deck is basic)."""
    return sum(len(p.energyCards) for _, _, p in _my_pokemon(my_state))


def _active_bolt_ready(my_state) -> bool:
    """Active is a Raging Bolt with the {L}{F} attack cost attached."""
    act = my_state.active[0] if my_state.active else None
    if act is None or act.id != Raging_Bolt_ex:
        return False
    return (EnergyType.LIGHTNING in act.energies) and (EnergyType.FIGHTING in act.energies)


def _missing_core(my_state) -> tuple[Pokemon | None, list[EnergyType]]:
    """The priority Raging Bolt (active first, then most-fueled bench copy) and the core types
    ({L}/{F}) it still lacks. Returns (None, []) when no Bolt is in play or its core is complete."""
    bolts = [p for _, _, p in _my_pokemon(my_state) if p.id == Raging_Bolt_ex]
    if not bolts:
        return None, []
    act = my_state.active[0] if my_state.active else None
    if act is not None and act.id == Raging_Bolt_ex:
        target = act
    else:
        target = max(bolts, key=lambda p: sum(1 for t in CORE_TYPES if t in p.energies))
    missing = [t for t in CORE_TYPES if t not in target.energies]
    return target, missing


def _kill_options(my_state, op_state, fairy_zone: bool = False) -> dict:
    """What Bellowing Thunder could KO right now: the current defender and the best gustable
    bench target. Fuel is board-wide (the attack discards from any of my Pokémon). `ready`
    also covers an armed BENCH Bolt that can reach the active spot this turn (free/cheap
    retreat), so Boss -> retreat -> attack lines light up."""
    fuel = _board_fuel(my_state)
    ready = _active_bolt_ready(my_state)
    if not ready:
        act = my_state.active[0] if my_state.active else None
        latias = any(p is not None and p.id == Latias_ex
                     for p in list(my_state.active or []) + list(my_state.bench))
        bench_armed = any(p is not None and p.id == Raging_Bolt_ex
                          and all(t in p.energies for t in CORE_TYPES) for p in my_state.bench)
        if (bench_armed and act is not None and act.id != Raging_Bolt_ex
                and (latias or card_table[act.id].retreatCost <= 1)):
            ready = True
    my_need = len(my_state.prize)
    out = {"ready": ready, "fuel": fuel, "act_kill": False, "act_prizes": 0, "act_wins": False,
           "bench_i": -1, "bench_prizes": 0, "bench_wins": False}
    act = op_state.active[0] if op_state.active and op_state.active[0] is not None else None
    if act is not None and ready and _k_needed(act, fairy_zone) <= fuel:
        out["act_kill"] = True
        out["act_prizes"] = prize_count(act)
        out["act_wins"] = out["act_prizes"] >= my_need
    best = -1
    for i, p in enumerate(op_state.bench):
        if p is None or not ready or _k_needed(p, fairy_zone) > fuel:
            continue
        pr = prize_count(p)
        if pr > out["bench_prizes"] or (pr == out["bench_prizes"] and best >= 0
                                        and _k_needed(p, fairy_zone) < _k_needed(op_state.bench[best], fairy_zone)):
            out["bench_prizes"] = pr
            best = i
    out["bench_i"] = best
    out["bench_wins"] = out["bench_prizes"] >= my_need
    # A gust is worth it when it converts a KO the current defender doesn't offer, or a bigger one.
    out["gust_worth"] = best >= 0 and (out["bench_wins"] or not out["act_kill"]
                                       or out["bench_prizes"] > out["act_prizes"])
    return out


def _finish(scores: list[int], select, want: int | None = None) -> list[int]:
    """Sort options by score desc and return the top-k indices. Unlike the other rule-based agents
    (which always take maxCount), k is overridable: Bellowing Thunder's discard select has
    minCount=0 / maxCount=<all my energy>, where taking maxCount would torch the whole board."""
    order = sorted(range(len(scores)), key=lambda i: (-scores[i], i))
    k = select.maxCount if want is None else want
    k = max(select.minCount, min(select.maxCount, k))
    return order[:k]


def agent(obs_dict: dict) -> list[int]:
    """Main Agent Function.

    Each element in the returned list must be >= 0 and < len(obs.select.option).
    The list length must be between obs.select.minCount and obs.select.maxCount (inclusive),
    with no duplicate elements.

    Returns:
        list[int]: A list of option index.
    """
    global pre_turn, pending_attach_type

    obs = to_observation_class(obs_dict)
    if obs.select is None:
        # Kaggle flow first call: return the deck and reset per-game state.
        pre_turn = -1
        pending_attach_type = None
        return my_deck

    state = obs.current
    select = obs.select
    context = select.context
    my_index = state.yourIndex
    my_state = state.players[my_index]
    op_state = state.players[1 - my_index]

    if state.turn != pre_turn:
        pre_turn = state.turn
        pending_attach_type = None

    eff = select.effect
    eff_id = eff.id if eff is not None else 0

    # ---- board census ----------------------------------------------------------------------
    mine = _my_pokemon(my_state)
    field_counts = defaultdict(int)
    for _, _, p in mine:
        field_counts[p.id] += 1
    hand_counts = defaultdict(int)
    for c in my_state.hand:
        hand_counts[c.id] += 1
    discard_counts = defaultdict(int)
    for c in my_state.discard:
        discard_counts[c.id] += 1
    attached_counts = defaultdict(int)
    for _, _, p in mine:
        for ec in p.energyCards:
            attached_counts[ec.id] += 1

    stadium_id = 0
    for c in state.stadium:
        stadium_id = c.id

    latias_in_play = field_counts[Latias_ex] > 0
    ogerpon_in_play = field_counts[Teal_Mask_Ogerpon_ex]
    tera_in_play = ogerpon_in_play + field_counts[Wellspring_Ogerpon_ex] > 0
    ogerpon_target = 3 if (stadium_id == Area_Zero_Underdepths and my_state.benchMax >= 8) else 2
    trash_energy = sum(discard_counts[e] for e in ENERGY_IDS)
    deck_energy_by_id = {e: max(0, DECK_ENERGY_TOTALS[e] - hand_counts[e] - discard_counts[e]
                                - attached_counts[e]) for e in ENERGY_IDS}
    deck_energy_left = sum(deck_energy_by_id.values())
    supporter_in_hand = any(card_table[c.id].cardType == CardType.SUPPORTER for c in my_state.hand)
    total_in_play = len(mine)

    opp_field = [p for p in list(op_state.active or []) + list(op_state.bench) if p is not None]
    opp_has_dragon = any(p.id in card_table
                         and card_table[p.id].energyType == EnergyType.DRAGON for p in opp_field)
    opp_big_hitter = _opp_big_hitter(op_state)
    fairy_zone = field_counts[Lillie_Clefairy_ex] > 0 and opp_has_dragon
    opp_stadium_threat = stadium_id != 0 and stadium_id != Area_Zero_Underdepths
    wellspring_needs_water = (field_counts[Wellspring_Ogerpon_ex] > 0
                              and not any(p.id == Wellspring_Ogerpon_ex
                                          and EnergyType.WATER in p.energies for _, _, p in mine))

    core_bolt, core_missing = _missing_core(my_state)
    if core_bolt is None:
        # No Bolt in play yet: the "missing core" is whatever {L}/{F} we hold NOWHERE (hand or
        # board). With only 2 of each in this list, Crispin must bank them before the Bolt lands
        # or the attack never comes online (measured: turn-20 first attacks without this).
        core_missing = [t for t in CORE_TYPES
                        if hand_counts[Lightning_Energy if t == EnergyType.LIGHTNING
                                       else Fighting_Energy] == 0
                        and attached_counts[Lightning_Energy if t == EnergyType.LIGHTNING
                                            else Fighting_Energy] == 0]
    kills = _kill_options(my_state, op_state, fairy_zone)
    # Stall: a Bolt lacks its {L}{F} core and the hand has no way to finish it. Only 2 {L} and
    # 2 {F} in this list, so also track a hard brick: a missing core type gone from every zone.
    missing_ids = [e for e in CORE_ENERGY_IDS if card_table[e].energyType in core_missing]
    missing_in_hand = any(hand_counts[e] > 0 for e in missing_ids)
    crispin_fixable = hand_counts[Crispin] > 0 and any(deck_energy_by_id[e] > 0 for e in missing_ids)
    eswitch_fixable = (hand_counts[Energy_Switch] > 0 and core_bolt is not None
                       and any(p.serial != core_bolt.serial
                               and any(card_table[ec.id].energyType in core_missing
                                       for ec in p.energyCards if ec.id in card_table)
                               for _, _, p in mine))
    retrieval_fixable = (hand_counts[Energy_Retrieval] + hand_counts[Night_Stretcher] > 0
                         and any(discard_counts[e] > 0 for e in missing_ids))
    stalled = (bool(core_missing) and not missing_in_hand and not crispin_fixable
               and not eswitch_fixable and not retrieval_fixable)
    core_bricked = any(deck_energy_by_id[e] == 0 and hand_counts[e] == 0
                       and discard_counts[e] == 0 and attached_counts[e] == 0
                       for e in missing_ids)

    # ---- per-hand-index usefulness (Ultra Ball cost, "dead hand" gates) ----------------------
    grass_keep = max(1, ogerpon_in_play)  # grass copies worth holding as Teal Dance fodder
    hand_usefulness = []
    seen = defaultdict(int)
    for c in my_state.hand:
        cid = c.id
        u = -10
        if cid == Raging_Bolt_ex:
            u = 200 if field_counts[cid] + seen[cid] < 2 else -30
        elif cid == Teal_Mask_Ogerpon_ex:
            u = 200 if field_counts[cid] + seen[cid] < ogerpon_target else -30
        elif cid == Latias_ex:
            u = 180 if field_counts[cid] + seen[cid] < 1 else -40
        elif cid == Meowth_ex:
            u = 120 if not supporter_in_hand and field_counts[cid] + seen[cid] < 2 else -20
        elif cid == Fezandipiti_ex:
            u = 60 if seen[cid] == 0 and field_counts[cid] == 0 else -30
        elif cid == Mega_Kangaskhan_ex:
            u = -20
        elif cid == Wellspring_Ogerpon_ex:
            u = 50 if field_counts[cid] == 0 else -30
        elif cid == Lillie_Clefairy_ex:
            u = 100 if opp_has_dragon and field_counts[cid] == 0 else -25
        elif cid == Chien_Pao:
            u = 60 if opp_stadium_threat and field_counts[cid] == 0 else -20
        elif cid == Passimian:
            u = 40 if field_counts[cid] == 0 and len(op_state.prize) <= 3 else -25
        elif cid in CORE_ENERGY_IDS:
            u = 200 if core_missing else 60  # only 2 of each: precious even as bank
        elif cid == Grass_Energy:
            u = 100 if seen[cid] < grass_keep else -20
        elif cid == Water_Energy:
            u = 90 if wellspring_needs_water or hand_counts[Wellspring_Ogerpon_ex] > 0 else 30
        elif cid == Psychic_Energy:
            u = 90 if (opp_has_dragon and field_counts[Lillie_Clefairy_ex]
                       + hand_counts[Lillie_Clefairy_ex] > 0) else 30
        elif cid == Crispin:
            u = 150
        elif cid == Boss_Orders:
            u = 120
        elif cid == Unfair_Stamp:
            u = 150  # the one hand-reset item: never pitch it
        elif cid == Cyrano:
            u = 80 if total_in_play < 4 else -10
        elif cid == Ciphermaniac:
            u = 20
        elif cid == Ultra_Ball:
            u = 80
        elif cid == Energy_Switch:
            u = 60 if seen[cid] < 2 else -10
        elif cid == Energy_Retrieval:
            u = 50 if trash_energy >= 1 else -10
        elif cid == Night_Stretcher:
            u = 50
        elif cid == Glass_Trumpet:
            u = 30 if trash_energy >= 1 else -15
        elif cid == Area_Zero_Underdepths:
            u = 40 if stadium_id != Area_Zero_Underdepths and seen[cid] == 0 else -50
        hand_usefulness.append(u)
        seen[cid] += 1
    useful_hand = sum(1 for u in hand_usefulness if u > 0)

    # ==========================================================================================
    # Context-specific selects with their own semantics
    # ==========================================================================================

    if context == SelectContext.IS_FIRST:
        # Guide: choose to go SECOND (Crispin + attack on our first turn).
        scores = [1 if o.type == OptionType.NO else 0 for o in select.option]
        return _finish(scores, select)

    if context == SelectContext.ACTIVATE:
        # "Would you like to activate the effect?" — keyed on the card asking.
        ctx_card = select.contextCard
        cid = ctx_card.id if ctx_card is not None else eff_id
        yes = True
        if cid == Chien_Pao:
            # Snow Sink discards ANY stadium, including our own Area Zero: only nuke the opponent's.
            yes = opp_stadium_threat
        elif cid == Wellspring_Ogerpon_ex:
            # Torrential Pump's extra: shuffle 3 of its energy for 120 to the bench.
            # Only worth it when that converts a bench KO.
            yes = any(p is not None and p.hp <= 120 for p in op_state.bench)
        scores = [1 if ((o.type == OptionType.YES) == yes) else 0 for o in select.option]
        return _finish(scores, select)

    if context == SelectContext.DAMAGE:
        # Effect-damage target pick (Cruel Arrow 100 anywhere / Torrential Pump 120 to bench):
        # take the KO worth the most prizes, else soften the biggest piece toward a cheaper
        # Bellowing (each 70 saved is one fewer discard next turn).
        dmg = 120 if eff_id == Wellspring_Ogerpon_ex else 100
        scores = []
        for o in select.option:
            pi = o.playerIndex if o.playerIndex is not None else 1 - my_index
            p = get_card(obs, o.area, o.index, pi)
            s = 0
            if p is not None and isinstance(p, Pokemon):
                if pi == my_index:
                    s = -1000
                else:
                    pr = prize_count(p)
                    if p.hp <= dmg:
                        s = 100000 if pr >= len(my_state.prize) else 10000 + pr * 1000 - p.hp
                    else:
                        saved = ceil(p.hp / 70) - ceil(max(p.hp - dmg, 10) / 70)
                        s = pr * 300 + saved * 400 - (p.hp - dmg) // 10
            scores.append(s)
        return _finish(scores, select)

    if context == SelectContext.DISCARD_ENERGY_CARD:
        # Bellowing Thunder's discard: 70 damage per card. Pick exactly enough for the KO,
        # spending renewable/bank fuel before the attacker's own {L}{F} core.
        defender = op_state.active[0] if op_state.active and op_state.active[0] is not None else None
        k = _k_needed(defender, fairy_zone) if defender is not None else 0
        infos = []
        for o in select.option:
            host = get_card(obs, o.area, o.index, my_index)
            eid = 0
            if host is not None and o.energyIndex is not None and o.energyIndex < len(host.energyCards):
                eid = host.energyCards[o.energyIndex].id
            infos.append((host, o.area, eid))
        # rank: 0.1 doomed-attacker fuel < 0.5 grass-on-Ogerpon (Teal Dance renews) < 1 bank
        # (Kangaskhan/Meowth; Glass Trumpet recycles) < 2 grass elsewhere < 3 misc off-attacker
        # < 4 surplus L/F on the attacker < 5 plan energy ({W} on Wellspring / {P} on Clefairy in
        # a Dragon matchup) < 6 core on a backup Bolt (undoes the pre-arm) < 9 the attacker's
        # last {L}/{F} (breaks next turn's attack; spend only for the KO).
        my_act = my_state.active[0] if my_state.active else None
        doomed = my_act is not None and _opp_can_ohko(op_state, my_act.hp)
        core_seen = {EnergyType.LIGHTNING: False, EnergyType.FIGHTING: False}
        ranks = []
        for host, area, eid in infos:
            hid = host.id if host is not None else 0
            etype = card_table[eid].energyType if eid in card_table else None
            on_attacker = hid == Raging_Bolt_ex and area == AreaType.ACTIVE
            if doomed and on_attacker:
                r = 0.1  # doomed fuel burns first
            elif hid == Teal_Mask_Ogerpon_ex and eid == Grass_Energy:
                r = 0.5
            elif hid in BATTERY_IDS:
                r = 1
            elif eid == Grass_Energy:
                r = 2
            elif hid == Wellspring_Ogerpon_ex and eid == Water_Energy:
                r = 5  # the only {W} in the deck powers Torrential Pump
            elif hid == Lillie_Clefairy_ex and eid == Psychic_Energy and opp_has_dragon:
                r = 5  # Fairy Zone Rondo fuel in the matchup it wins
            elif hid == Raging_Bolt_ex and not on_attacker and etype in CORE_TYPES:
                r = 6  # backup Bolt's pre-armed core
            elif not on_attacker:
                r = 3
            else:  # L/F on a surviving attacker: keep one of each if we can
                if etype in core_seen and not core_seen[etype]:
                    core_seen[etype] = True
                    r = 9
                else:
                    r = 4
            ranks.append(r)
        scores = [100000 - int(r * 1000) - i for i, r in enumerate(ranks)]
        if k and k <= len(infos):
            want = k
        else:
            # No KO available: chip only with free fuel — renewable Ogerpon grass plus anything
            # on a doomed attacker (it's lost either way). Never bleed the rest.
            want = min(sum(1 for r in ranks if r <= 0.5), k)
        return _finish(scores, select, want=want)

    if context in (SelectContext.SETUP_ACTIVE_POKEMON,):
        # Start the attacker itself: it never needs to move (measured lesson from the simple
        # agent). Kangaskhan's draw wants the Active Spot but is a 3-retreat, 3-prize trap
        # without Latias; utility bodies stay off the front.
        setup_active = {Raging_Bolt_ex: 100, Teal_Mask_Ogerpon_ex: 90, Mega_Kangaskhan_ex: 60,
                        Latias_ex: 55, Wellspring_Ogerpon_ex: 50, Lillie_Clefairy_ex: 40,
                        Fezandipiti_ex: 35, Meowth_ex: 30, Chien_Pao: 25, Passimian: 20}
        scores = []
        for o in select.option:
            c = get_card(obs, o.area, o.index, my_index)
            scores.append(setup_active.get(c.id, 0) if c is not None else 0)
        return _finish(scores, select)

    if context == SelectContext.SETUP_BENCH_POKEMON:
        # Bench the engine pieces; hold Meowth and Chien-Pao (their abilities only trigger on an
        # in-game bench play) and Kangaskhan (3-prize liability). Engine loops one slot at a time.
        seen_bench = defaultdict(int)
        for _, _, p in mine:
            seen_bench[p.id] += 1
        scores = []
        for o in select.option:
            c = get_card(obs, o.area, o.index, my_index)
            s = -1
            if c is not None:
                cid = c.id
                if cid == Teal_Mask_Ogerpon_ex:
                    s = 100 if seen_bench[cid] < 1 else (95 if seen_bench[cid] < 2 else -1)
                elif cid == Raging_Bolt_ex:
                    s = 90 if seen_bench[cid] < 1 else (50 if seen_bench[cid] < 2 else -1)
                elif cid == Latias_ex:
                    s = 70 if seen_bench[cid] < 1 else -1
                elif cid == Fezandipiti_ex:
                    s = 10 if seen_bench[cid] < 1 else -1
                elif cid == Mega_Kangaskhan_ex:
                    s = 5 if seen_bench[cid] < 1 else -1  # 3-prize risk < bench-out insurance
            scores.append(s)
        return _finish(scores, select, want=sum(1 for s in scores if s > 0))

    if context in (SelectContext.SWITCH, SelectContext.TO_ACTIVE):
        scores = []
        for o in select.option:
            p = get_card(obs, o.area, o.index, o.playerIndex if o.playerIndex is not None else my_index)
            s = 0
            if p is None:
                scores.append(s)
                continue
            if o.playerIndex is not None and o.playerIndex != my_index:
                # Gust pick (Boss's Orders): drag up what we can KO, else the weakest
                # high-value piece.
                if kills["ready"] and _k_needed(p, fairy_zone) <= kills["fuel"]:
                    s = 100000 + prize_count(p) * 1000
                    if prize_count(p) >= len(my_state.prize):
                        s += 50000
                else:
                    s = prize_count(p) * 1000 + 150 * len(p.energies) - p.hp
            else:
                # Promoting my own next active.
                cid = p.id
                op_act = op_state.active[0] if op_state.active and op_state.active[0] is not None else None
                if cid == Raging_Bolt_ex:
                    core_ok = all(t in p.energies for t in CORE_TYPES)
                    s = (1000 if core_ok else 600) + 10 * len(p.energies)
                elif cid == Teal_Mask_Ogerpon_ex:
                    s = 400 + 10 * len(p.energies)
                elif cid == Wellspring_Ogerpon_ex:
                    s = 350 + 10 * len(p.energies)
                elif cid == Lillie_Clefairy_ex:
                    s = 320
                    if (fairy_zone and op_act is not None
                            and _attack_damage(ATK_RONDO, my_state, op_state, op_act,
                                               total_in_play, fairy_zone, p) >= op_act.hp):
                        s += 400
                elif cid == Mega_Kangaskhan_ex:
                    s = 300 + (200 if latias_in_play else 0)
                    if len(op_state.prize) <= 3:
                        s -= 400  # a Kangaskhan KO would hand over the last 3 prizes
                    if opp_big_hitter:
                        s -= 250  # 2HKO'd for free by 150+ base hitters (Phantom Dive decks)
                elif cid == Latias_ex:
                    s = 200
                elif cid == Fezandipiti_ex:
                    s = 150
                elif cid in ONE_PRIZE_IDS:
                    # 1-prize speed bumps: promote them late so ex trades stop paying.
                    s = 130 + (300 if len(op_state.prize) <= 2 else 0)
                elif cid == Meowth_ex:
                    s = 100
                # An armed secondary that KOs the defender outranks every draw-engine promotion
                # (this keeps the SWITCH pick aligned with the retreat trigger below).
                if op_act is not None and cid != Raging_Bolt_ex:
                    for aid in card_table[cid].attacks:
                        a = attack_table.get(aid)
                        if (a is not None and len(p.energies) >= len(a.energies)
                                and _attack_damage(aid, my_state, op_state, op_act,
                                                   total_in_play, fairy_zone, p) >= op_act.hp):
                            s += 800
                            break
                if _opp_can_ohko(op_state, p.hp):
                    # The promotee likely dies on their next turn: weigh the prizes it feeds.
                    s -= 300 * prize_count(p)
            scores.append(s)
        return _finish(scores, select)

    if context == SelectContext.TO_HAND:
        scores = []
        for o in select.option:
            c = get_card(obs, o.area, o.index, my_index)
            s = 0
            if c is not None:
                s = _search_pick_score(c.id, eff_id, field_counts, hand_counts, core_missing,
                                       supporter_in_hand, ogerpon_in_play, ogerpon_target,
                                       kills, my_state, state, op_state, opp_has_dragon,
                                       opp_stadium_threat, wellspring_needs_water, total_in_play,
                                       deck_energy_by_id)
                if card_table[c.id].cardType != CardType.BASIC_ENERGY:
                    s -= 100 * hand_counts[c.id]  # diversify Pokémon/trainer picks, not energy
            scores.append(s)
        return _finish(scores, select)

    if context == SelectContext.TO_DECK and eff_id == Ciphermaniac:
        # Ciphermaniac's Codebreaking: stack the two cards that fix the current blocker on top.
        # Only played when a controlled draw (Run Errand / Teal Dance) can lift them this turn.
        scores = []
        for o in select.option:
            c = get_card(obs, o.area, o.index, my_index)
            s = 1
            if c is not None:
                cid = c.id
                et = card_table[cid].energyType if cid in card_table else None
                if et in core_missing:
                    s = 300 if et == EnergyType.FIGHTING else 290
                elif cid == Energy_Switch and eswitch_fixable:
                    s = 250
                elif cid == Boss_Orders and kills["gust_worth"]:
                    s = 240
                elif cid == Crispin:
                    s = 230
                elif et in CORE_TYPES:
                    s = 200
                elif cid == Boss_Orders:
                    s = 150
                elif et == EnergyType.GRASS:
                    s = 100
            scores.append(s)
        return _finish(scores, select)

    if context == SelectContext.ATTACH_TO:
        # Picking WHICH energy card gets attached (Teal Dance hand grass, Crispin's deck attach,
        # Glass Trumpet's trash energy).
        scores = []
        for o in select.option:
            c = get_card(obs, o.area, o.index, my_index)
            s = 1
            if c is not None:
                et = card_table[c.id].energyType if c.id in card_table else None
                if et in core_missing:
                    s = 300 if et == EnergyType.FIGHTING else 290
                elif eff_id == Glass_Trumpet and et in CORE_TYPES:
                    s = 250  # bank scarce {L}/{F} on the battery: Energy Switch routes it later
                elif et == EnergyType.WATER and wellspring_needs_water:
                    s = 170
                elif et == EnergyType.PSYCHIC and field_counts[Lillie_Clefairy_ex] > 0 and opp_has_dragon:
                    s = 160
                elif et in CORE_TYPES:
                    s = 150
                elif et == EnergyType.GRASS:
                    s = 100
            scores.append(s)
        pick = _finish(scores, select)
        if pick:
            c = get_card(obs, select.option[pick[0]].area, select.option[pick[0]].index, my_index)
            if c is not None and c.id in card_table:
                pending_attach_type = card_table[c.id].energyType
        return pick

    if context == SelectContext.SWITCH_ENERGY_CARD:
        # Energy Switch source: pull a core-type energy off any host EXCEPT the Bolt being
        # assembled (a bench Bolt's spare {F} moving to the active Bolt is a fine source).
        scores = []
        for o in select.option:
            host = get_card(obs, o.area, o.index, my_index)
            s = -1
            eid = 0
            if host is not None and o.energyIndex is not None and o.energyIndex < len(host.energyCards):
                eid = host.energyCards[o.energyIndex].id
            et = card_table[eid].energyType if eid in card_table else None
            not_target = host is not None and (core_bolt is None or host.serial != core_bolt.serial)
            if et in core_missing and not_target:
                s = 1000
            elif (et == EnergyType.WATER and wellspring_needs_water
                    and host is not None and host.id != Wellspring_Ogerpon_ex):
                s = 300
            elif et in CORE_TYPES and not_target and host.id != Raging_Bolt_ex:
                s = 200
            elif et == EnergyType.GRASS and host is not None and host.id != Teal_Mask_Ogerpon_ex:
                s = 50
            scores.append(s)
        pick = _finish(scores, select)
        if pick:
            o = select.option[pick[0]]
            host = get_card(obs, o.area, o.index, my_index)
            if host is not None and o.energyIndex is not None and o.energyIndex < len(host.energyCards):
                eid = host.energyCards[o.energyIndex].id
                if eid in card_table:
                    pending_attach_type = card_table[eid].energyType
        return pick

    if context == SelectContext.ATTACH_FROM:
        # Picking WHICH of my Pokémon receives an energy (manual attach, Crispin's attach half,
        # Energy Switch destination, Glass Trumpet bench targets).
        et = pending_attach_type
        if eff_id in ENERGY_IDS:
            et = card_table[eff_id].energyType  # manual attach: the effect IS the energy card
        # A stuck non-attacker active with an unpayable retreat cost blocks the whole plan when a
        # ready Bolt waits on the bench: funding its retreat beats any other attach target.
        act = my_state.active[0] if my_state.active else None
        ready_bench = any(p is not None and p.id == Raging_Bolt_ex
                          and all(t in p.energies for t in CORE_TYPES) for p in my_state.bench)
        fund_retreat = (act is not None and act.id != Raging_Bolt_ex and ready_bench
                        and not latias_in_play
                        and len(act.energies) < card_table[act.id].retreatCost)
        scores = []
        for o in select.option:
            p = get_card(obs, o.area, o.index, my_index)
            s = 0
            if p is not None:
                cid = p.id
                if fund_retreat and o.area == AreaType.ACTIVE and eff_id != Glass_Trumpet:
                    scores.append(1100)
                    continue
                if eff_id == Glass_Trumpet:
                    s = 100 if cid == Mega_Kangaskhan_ex else 90 if cid == Meowth_ex else 10
                elif core_bricked and cid == Mega_Kangaskhan_ex:
                    s = 950  # Bolt plan dead: arm Rapid-Fire instead
                elif et in CORE_TYPES:
                    if cid == Raging_Bolt_ex and et not in p.energies:
                        s = 1000 if o.area == AreaType.ACTIVE else 900  # incl. backup pre-arm
                    elif cid == Raging_Bolt_ex:
                        s = 500
                    elif cid in BATTERY_IDS:
                        s = 300
                    elif cid == Teal_Mask_Ogerpon_ex:
                        s = 250
                    else:
                        s = 100
                elif et == EnergyType.WATER:
                    if cid == Wellspring_Ogerpon_ex and EnergyType.WATER not in p.energies:
                        s = 900
                    elif cid == Chien_Pao:
                        s = 350
                    elif cid in BATTERY_IDS:
                        s = 300
                    else:
                        s = 100
                elif et == EnergyType.PSYCHIC:
                    if cid == Lillie_Clefairy_ex:
                        s = 900 if opp_has_dragon else 400
                    elif cid == Latias_ex:
                        s = 300
                    elif cid in BATTERY_IDS:
                        s = 250
                    else:
                        s = 100
                elif et == EnergyType.GRASS:
                    s = {Teal_Mask_Ogerpon_ex: 800, Mega_Kangaskhan_ex: 300, Meowth_ex: 280,
                         Raging_Bolt_ex: 250}.get(cid, 100)
                else:
                    # Unknown energy type: favor completing a Bolt, then the fuel bank.
                    if cid == Raging_Bolt_ex and any(t not in p.energies for t in CORE_TYPES):
                        s = 1000 if o.area == AreaType.ACTIVE else 900
                    else:
                        s = {Teal_Mask_Ogerpon_ex: 400, Mega_Kangaskhan_ex: 300,
                             Meowth_ex: 280}.get(cid, 100)
            scores.append(s)
        return _finish(scores, select)

    if context == SelectContext.DISCARD:
        own_hand = [o for o in select.option
                    if o.area == AreaType.HAND and (o.playerIndex is None or o.playerIndex == my_index)]
        if own_hand:
            # Ultra Ball's cost (and any other hand discard): pitch the least useful cards.
            scores = []
            for o in select.option:
                if o.area == AreaType.HAND and o.index < len(hand_usefulness):
                    scores.append(-hand_usefulness[o.index])
                else:
                    scores.append(0)
            return _finish(scores, select)
        # Bench shrink (Area Zero leaving): dump spent utility bodies, keep anything fueled and
        # anything whose plan is still live (Clefairy in a Dragon matchup, late-game 1-prizers).
        scores = []
        for o in select.option:
            p = get_card(obs, o.area, o.index, my_index)
            s = 0
            if p is not None and isinstance(p, Pokemon):
                base = {Meowth_ex: 1000, Fezandipiti_ex: 800, Chien_Pao: 750, Passimian: 700,
                        Lillie_Clefairy_ex: 600, Teal_Mask_Ogerpon_ex: 300,
                        Wellspring_Ogerpon_ex: 280, Raging_Bolt_ex: 200, Latias_ex: 150,
                        Mega_Kangaskhan_ex: 100}.get(p.id, 0)
                if p.id == Lillie_Clefairy_ex and opp_has_dragon:
                    base = 100
                if p.id in ONE_PRIZE_IDS and len(op_state.prize) <= 2:
                    base = 250  # late game the 1-prize wall is the plan
                s = base - 300 * len(p.energies)
                if field_counts[p.id] > 1:
                    s += 200
            scores.append(s)
        return _finish(scores, select)

    if context == SelectContext.DISCARD_ENERGY:
        # Retreat cost: pay with grass before the plan types, core last.
        scores = []
        for o in select.option:
            et = None
            if o.energyIndex is not None:
                act = my_state.active[0] if my_state.active else None
                if act is not None and o.energyIndex < len(act.energies):
                    et = act.energies[o.energyIndex]
            scores.append(3 if et == EnergyType.GRASS else 1 if et in CORE_TYPES else 2)
        return _finish(scores, select)

    if context in (SelectContext.TO_DECK_ENERGY, SelectContext.TO_HAND_ENERGY):
        # Torrential Pump's shuffle-3 / Icicle Loop's bounce: give back grass first, keep the
        # deck's only {W} attached when there's a choice.
        scores = []
        for o in select.option:
            et = None
            if o.energyIndex is not None:
                act = my_state.active[0] if my_state.active else None
                if act is not None and o.energyIndex < len(act.energies):
                    et = act.energies[o.energyIndex]
            scores.append(3 if et == EnergyType.GRASS else 1 if et == EnergyType.WATER else 2)
        return _finish(scores, select)

    # ==========================================================================================
    # MAIN (and any remaining context): score-and-sort over the generic option types
    # ==========================================================================================

    can_dance = any(o.type == OptionType.ABILITY
                    and (p := get_card(obs, o.area, o.index, my_index)) is not None
                    and p.id == Teal_Mask_Ogerpon_ex
                    for o in select.option)
    controlled_draw = ((my_state.active and my_state.active[0] is not None
                        and my_state.active[0].id == Mega_Kangaskhan_ex)
                       or (can_dance and hand_counts[Grass_Energy] > 0))

    scores = []
    for o in select.option:
        score = 0
        if o.type == OptionType.NUMBER:
            score = o.number
        elif o.type == OptionType.YES:
            score = 1
        elif o.type == OptionType.PLAY:
            c = get_card(obs, AreaType.HAND, o.index, my_index)
            score = _play_score(c, obs, state, my_state, op_state, field_counts, hand_counts,
                                discard_counts, stadium_id, core_missing, kills, useful_hand,
                                hand_usefulness, total_in_play, ogerpon_in_play, ogerpon_target,
                                trash_energy, deck_energy_left, deck_energy_by_id, can_dance,
                                supporter_in_hand, mine, stalled, tera_in_play, opp_has_dragon,
                                opp_stadium_threat, latias_in_play, controlled_draw,
                                eswitch_fixable, opp_big_hitter)
        elif o.type == OptionType.ATTACH:
            # Manual attach arrives as one option per (hand energy card x target Pokémon): the
            # energy sits at (area=HAND, index), the target at (inPlayArea, inPlayIndex). Score
            # the PAIR — attaching the wrong type to the right target wastes the turn's one attach.
            ecard = get_card(obs, o.area, o.index, my_index)
            target = get_card(obs, o.inPlayArea, o.inPlayIndex, my_index)
            et = card_table[ecard.id].energyType if (ecard is not None and ecard.id in card_table) else None
            score = 8000
            if target is not None:
                act = my_state.active[0] if my_state.active else None
                ready_bench = any(p is not None and p.id == Raging_Bolt_ex
                                  and all(t in p.energies for t in CORE_TYPES) for p in my_state.bench)
                fund_retreat = (act is not None and act.id != Raging_Bolt_ex and ready_bench
                                and not latias_in_play
                                and len(act.energies) < card_table[act.id].retreatCost)
                if fund_retreat and o.inPlayArea == AreaType.ACTIVE:
                    # Pay the stuck active's retreat so the ready Bolt can promote; spend grass.
                    score = 9610 if et == EnergyType.GRASS else 9600
                elif core_bricked and target.id == Mega_Kangaskhan_ex:
                    # Bolt plan is dead ({L}/{F} bricked out of the game): pile ANY energy onto
                    # Kangaskhan — Rapid-Fire {C}{C}{C} 200 becomes the win condition.
                    score = 8600
                elif et in CORE_TYPES:
                    if target.id == Raging_Bolt_ex and et not in target.energies:
                        score = 9500 if o.inPlayArea == AreaType.ACTIVE else 9200
                    elif target.id == Raging_Bolt_ex:
                        score = 8150  # extra fuel rides on the attacker
                    elif target.id in BATTERY_IDS:
                        score = 8120
                    elif target.id == Teal_Mask_Ogerpon_ex:
                        score = 8110
                    else:
                        score = 8050
                elif et == EnergyType.WATER:
                    score = 8300 if (target.id == Wellspring_Ogerpon_ex
                                     and EnergyType.WATER not in target.energies) else 8010
                elif et == EnergyType.PSYCHIC:
                    if target.id == Lillie_Clefairy_ex and opp_has_dragon:
                        score = 8310
                    elif target.id == Latias_ex:
                        score = 8020
                    else:
                        score = 8010
                elif et == EnergyType.GRASS:
                    if can_dance:
                        score = -1  # Teal Dance attaches it AND draws
                    elif ogerpon_in_play and hand_counts[Grass_Energy] <= 1:
                        score = -1  # hold the last grass for next turn's dance
                    else:
                        score = {Teal_Mask_Ogerpon_ex: 8060, Mega_Kangaskhan_ex: 8040,
                                 Meowth_ex: 8030}.get(target.id, 8000)
        elif o.type == OptionType.ABILITY:
            p = get_card(obs, o.area, o.index, my_index)
            score = -1
            if p is not None:
                if p.id == Fezandipiti_ex:
                    score = 58000 if my_state.deckCount > 3 else -1
                elif p.id == Mega_Kangaskhan_ex:
                    score = 57000 if my_state.deckCount > 2 else -1
                elif p.id == Teal_Mask_Ogerpon_ex:
                    score = 55000 if my_state.deckCount > 1 else -1
                else:
                    score = 50000  # any other offered ability (Last-Ditch etc.): use it
        elif o.type == OptionType.RETREAT:
            score = _retreat_score(my_state, op_state, hand_counts, latias_in_play, fairy_zone,
                                   total_in_play, core_bricked)
        elif o.type == OptionType.ATTACK:
            score = _attack_score(o.attackId, my_state, op_state, kills, useful_hand,
                                  discard_counts, mine, stalled, fairy_zone, total_in_play,
                                  core_bricked)
        elif o.type == OptionType.EVOLVE:
            score = 110000  # no evolutions in this deck; harmless default
        elif o.type == OptionType.END:
            score = 0
        scores.append(score)

    return _finish(scores, select)


def _search_pick_score(cid, eff_id, field_counts, hand_counts, core_missing, supporter_in_hand,
                       ogerpon_in_play, ogerpon_target, kills, my_state, state, op_state,
                       opp_has_dragon, opp_stadium_threat, wellspring_needs_water, total_in_play,
                       deck_energy_by_id) -> int:
    """TO_HAND picks: deck/discard searches, branched on the activating card."""
    data = card_table.get(cid)
    et = data.energyType if data is not None else None
    if eff_id == Crispin:
        # Pick 1 of 2 (this one goes to HAND; the attach pick follows and must be a DIFFERENT
        # type). With both core types missing, take {L} now and let the attach half place {F}.
        # With exactly one missing, do NOT take it to hand (that would make it unattachable) —
        # take grass for Teal Dance or bank the other scarce core type instead.
        if len(core_missing) >= 2:
            if et == EnergyType.LIGHTNING:
                return 300
            if et == EnergyType.FIGHTING:
                return 290
            return 100 if et == EnergyType.GRASS else 50
        if len(core_missing) == 1:
            if et in core_missing:
                return 60  # leave the missing type for the attach half
            if et == EnergyType.GRASS and hand_counts[Grass_Energy] < 2 and ogerpon_in_play:
                return 300
            if et in CORE_TYPES:
                return 250  # bank the present core type (only 2 of each in the list)
            return 80
        # Core complete: stock the engine.
        if et == EnergyType.GRASS:
            return 250
        if et == EnergyType.WATER and wellspring_needs_water:
            return 150
        if et == EnergyType.PSYCHIC and (field_counts[Lillie_Clefairy_ex]
                                         + hand_counts[Lillie_Clefairy_ex] > 0) and opp_has_dragon:
            return 140
        if et in CORE_TYPES:
            return 130  # pre-arm fuel for the backup Bolt
        return 50
    bolt_missing = field_counts[Raging_Bolt_ex] + hand_counts[Raging_Bolt_ex] == 0
    if eff_id == Meowth_ex:
        # Last-Ditch Catch: fetch the Supporter this turn needs. With only 2 Bolts in the list,
        # finding the attacker outranks the energy engine while it's missing entirely.
        if cid == Cyrano and bolt_missing:
            return 310
        if cid == Crispin and (core_missing
                               or hand_counts[Lightning_Energy] + hand_counts[Fighting_Energy] < 2):
            return 300
        if cid == Boss_Orders and kills["gust_worth"]:
            return 280
        if cid == Cyrano:
            return 240 if total_in_play < 4 else 90
        if cid == Crispin:
            return 230
        if cid == Boss_Orders:
            return 100
        if cid == Ciphermaniac:
            return 60
        return 50
    if eff_id == Cyrano:
        # Up to 3 Pokémon ex (Mega Kangaskhan IS offered — confirmed in traces).
        if cid == Teal_Mask_Ogerpon_ex and field_counts[cid] + hand_counts[cid] < ogerpon_target:
            return 300
        if cid == Raging_Bolt_ex and field_counts[cid] + hand_counts[cid] < 2:
            return 280
        if cid == Latias_ex and field_counts[cid] + hand_counts[cid] < 1:
            return 260
        if (cid == Mega_Kangaskhan_ex and field_counts[cid] + hand_counts[cid] < 1
                and not _opp_big_hitter(op_state)):
            # No hand-reset supporter in this list: Run Errand IS the draw engine. A board
            # without it goes dead for many consecutive turns (measured in mirror losses).
            return 250
        if cid == Lillie_Clefairy_ex and opp_has_dragon and field_counts[cid] + hand_counts[cid] < 1:
            return 240
        if cid == Meowth_ex and not supporter_in_hand and field_counts[cid] == 0:
            return 200
        if cid == Fezandipiti_ex and field_counts[cid] + hand_counts[cid] < 1:
            return 150
        if cid == Wellspring_Ogerpon_ex and field_counts[cid] + hand_counts[cid] < 1:
            return 120
        return 30
    if eff_id in (Energy_Retrieval, Night_Stretcher):
        if et in core_missing:
            return 300 if et == EnergyType.FIGHTING else 290
        if cid == Raging_Bolt_ex and field_counts[cid] <= 1:
            return 250
        if et == EnergyType.GRASS:
            return 200 if hand_counts[Grass_Energy] == 0 and ogerpon_in_play else 120
        if et == EnergyType.WATER and wellspring_needs_water:
            return 160
        if et in CORE_TYPES:
            return 150
        if cid == Teal_Mask_Ogerpon_ex and field_counts[cid] < ogerpon_target:
            return 140
        return 50
    # Ultra Ball / generic deck search: fill the target board.
    if cid == Raging_Bolt_ex:
        if field_counts[cid] == 0:
            return 320
        if field_counts[cid] + hand_counts[cid] < 2:
            return 280
        return 30
    if cid == Teal_Mask_Ogerpon_ex:
        return 300 if field_counts[cid] + hand_counts[cid] < ogerpon_target else 30
    if cid == Latias_ex:
        return 260 if field_counts[cid] + hand_counts[cid] < 1 else 20
    if cid == Meowth_ex:
        return 240 if not supporter_in_hand and field_counts[cid] == 0 and not state.supporterPlayed else 20
    if cid == Lillie_Clefairy_ex:
        return 200 if opp_has_dragon and field_counts[cid] + hand_counts[cid] < 1 else 15
    if cid == Chien_Pao:
        return 90 if opp_stadium_threat and field_counts[cid] == 0 else 15
    if cid == Wellspring_Ogerpon_ex:
        return 80 if field_counts[cid] + hand_counts[cid] < 1 else 10
    if cid == Passimian:
        return 60 if field_counts[cid] == 0 and len(op_state.prize) <= 3 else 10
    if cid == Fezandipiti_ex:
        return 60 if field_counts[cid] + hand_counts[cid] < 1 else 10
    if cid == Mega_Kangaskhan_ex:
        return (210 if field_counts[cid] + hand_counts[cid] < 1
                and not _opp_big_hitter(op_state) else 50)  # the draw engine
    return 10


def _play_score(c, obs, state, my_state, op_state, field_counts, hand_counts, discard_counts,
                stadium_id, core_missing, kills, useful_hand, hand_usefulness, total_in_play,
                ogerpon_in_play, ogerpon_target, trash_energy, deck_energy_left,
                deck_energy_by_id, can_dance, supporter_in_hand, mine, stalled, tera_in_play,
                opp_has_dragon, opp_stadium_threat, latias_in_play, controlled_draw,
                eswitch_fixable, opp_big_hitter) -> int:
    """MAIN-phase PLAY option: the score band encodes within-turn ordering."""
    if c is None:
        return 0
    data = card_table[c.id]
    cid = c.id
    bench_room = my_state.benchMax - sum(1 for p in my_state.bench if p is not None)

    if data.cardType == CardType.POKEMON:
        # Bench-out safety valve: never be left with a lone active.
        if total_in_play <= 1:
            pref = {Teal_Mask_Ogerpon_ex: 0, Raging_Bolt_ex: 1, Latias_ex: 2, Fezandipiti_ex: 3,
                    Meowth_ex: 4, Wellspring_Ogerpon_ex: 5, Lillie_Clefairy_ex: 6, Chien_Pao: 7,
                    Passimian: 8, Mega_Kangaskhan_ex: 9}.get(cid, 10)
            return 200000 - pref
        if cid == Teal_Mask_Ogerpon_ex:
            return 100000 if field_counts[cid] < ogerpon_target else -1
        if cid == Raging_Bolt_ex:
            return 100000 if field_counts[cid] < 1 else (99500 if field_counts[cid] < 2 else -1)
        if cid == Latias_ex:
            return 100000 if field_counts[cid] < 1 else -1
        if cid == Meowth_ex:
            # Its whole point is the on-play Supporter search: bench it when we lack a supporter,
            # or lack CRISPIN specifically while the attack core is incomplete (Crispin is the
            # engine; a Boss in hand shouldn't block fetching it). Three copies: a later Meowth
            # re-fetches, so allow a second body.
            need_crispin = bool(core_missing) and hand_counts[Crispin] == 0
            return 99000 if (field_counts[cid] < 2 and not state.supporterPlayed
                             and (not supporter_in_hand or need_crispin)) else -1
        if cid == Chien_Pao:
            # Snow Sink counter-stadium (the ACTIVATE handler declines on our own Area Zero).
            return 50000 if opp_stadium_threat and field_counts[cid] == 0 else -1
        if cid == Lillie_Clefairy_ex:
            return 45500 if opp_has_dragon and field_counts[cid] == 0 else -1
        if cid == Wellspring_Ogerpon_ex:
            water_reachable = (hand_counts[Water_Energy] > 0 or deck_energy_by_id[Water_Energy] > 0
                               or discard_counts[Water_Energy] > 0)
            return 18000 if (field_counts[cid] == 0 and state.turn >= 2 and water_reachable
                             and bench_room >= 2) else -1
        if cid == Passimian:
            return 17000 if (field_counts[cid] == 0 and len(op_state.prize) <= 3
                             and bench_room >= 2) else -1
        if cid == Fezandipiti_ex:
            return 20000 if (state.turn >= 3 and field_counts[cid] == 0 and bench_room >= 2) else -1
        if cid == Mega_Kangaskhan_ex:
            # 3-prize liability, but the ONLY repeatable draw in the list: a board without it
            # goes dead (measured). Bench it early — never into the opponent's last 3 prizes,
            # and never against a board that 2HKOs it for free (measured dragapult regression).
            return 21000 if ((latias_in_play or field_counts[cid] == 0)
                             and len(op_state.prize) >= 4 and useful_hand <= 5
                             and field_counts[cid] == 0 and bench_room >= 1
                             and not opp_big_hitter) else -1
        return -1

    if data.cardType == CardType.BASIC_ENERGY:
        # Manual attach (the once-per-turn resource). Grass is Teal Dance fodder first.
        et = data.energyType
        if et in CORE_TYPES:
            for _, _, p in mine:
                if p.id == Raging_Bolt_ex and et not in p.energies:
                    return 9500
            return 8100
        if et == EnergyType.GRASS:
            if can_dance:
                return -1  # let Teal Dance attach it (same attach + a free card)
            if ogerpon_in_play and hand_counts[Grass_Energy] <= 1:
                return -1  # hold the last grass for next turn's dance
            return 8000
        return 8000

    if data.cardType == CardType.SUPPORTER:
        if cid == Boss_Orders:
            if kills["gust_worth"] and kills["bench_wins"]:
                return 130000  # gust for game
            # A gustable KO means the attack already works without Crispin's help this turn,
            # so converting it outranks every other supporter.
            return 27000 if kills["gust_worth"] else -1
        if cid == Crispin:
            if deck_energy_left <= 0:
                return -1
            if core_missing or hand_counts[Lightning_Energy] + hand_counts[Fighting_Energy] < 2:
                return 26000
            return 24000
        if cid == Cyrano:
            if field_counts[Raging_Bolt_ex] + hand_counts[Raging_Bolt_ex] == 0:
                return 26500  # no attacker anywhere: finding a Bolt outranks the energy engine
            thin = (field_counts[Teal_Mask_Ogerpon_ex] + hand_counts[Teal_Mask_Ogerpon_ex] < 2
                    or field_counts[Raging_Bolt_ex] + hand_counts[Raging_Bolt_ex] < 2
                    or field_counts[Latias_ex] + hand_counts[Latias_ex] < 1)
            return 25000 if thin else -1
        if cid == Ciphermaniac:
            # Narrow stall-breaker only: without a controlled draw (Run Errand / Teal Dance) the
            # stacked cards get shuffled away by the next search, and Crispin strictly dominates
            # as the energy supporter otherwise.
            return 15000 if stalled and controlled_draw else -1
        return -1

    if data.cardType == CardType.STADIUM:
        if cid == Area_Zero_Underdepths and stadium_id != Area_Zero_Underdepths and tera_in_play:
            want_more = (hand_counts[Teal_Mask_Ogerpon_ex] > 0 or hand_counts[Raging_Bolt_ex] > 0
                         or hand_counts[Latias_ex] > 0)
            if len(my_state.bench) >= my_state.benchMax and want_more:
                return 110000  # unlock the bench before this turn's Pokémon plays
            if len(my_state.bench) >= 4 or stadium_id != 0:
                return 30000
        return -1

    # Items
    if cid == Unfair_Stamp:
        # Above the draw abilities' band so it fires BEFORE we draw cards it would shuffle away.
        # The engine gates legality (our Pokémon KO'd last turn); we gate on it actually hurting:
        # our hand is dead and theirs isn't.
        return 70000 if (useful_hand <= 3 and op_state.handCount >= 4) else -1
    if cid == Ultra_Ball:
        if field_counts[Raging_Bolt_ex] + hand_counts[Raging_Bolt_ex] == 0:
            return 46000  # no attacker anywhere: pay any 2 cards to find one
        expendable = sum(1 for u in hand_usefulness if u <= 0) - (1 if hand_usefulness else 0)
        wanted = (field_counts[Teal_Mask_Ogerpon_ex] + hand_counts[Teal_Mask_Ogerpon_ex] < ogerpon_target
                  or field_counts[Raging_Bolt_ex] + hand_counts[Raging_Bolt_ex] < 2
                  or field_counts[Latias_ex] + hand_counts[Latias_ex] < 1)
        return 45000 if expendable >= 2 and wanted else -1
    if cid == Energy_Switch:
        if core_missing and eswitch_fixable:
            return 60000
        return -1
    if cid == Energy_Retrieval:
        missing_in_trash = any(discard_counts[e] > 0 for e in CORE_ENERGY_IDS
                               if card_table[e].energyType in core_missing)
        if missing_in_trash:
            return 62000  # the reload loop: trash -> hand -> manual attach -> attack
        if trash_energy >= 2:
            return 61000
        return 40000 if trash_energy == 1 else -1
    if cid == Night_Stretcher:
        needs = ((core_missing and any(discard_counts[e] > 0 for e in CORE_ENERGY_IDS))
                 or (discard_counts[Raging_Bolt_ex] > 0 and field_counts[Raging_Bolt_ex] <= 1)
                 or (discard_counts[Teal_Mask_Ogerpon_ex] > 0
                     and field_counts[Teal_Mask_Ogerpon_ex] < ogerpon_target))
        return 44000 if needs else -1
    if cid == Glass_Trumpet:
        bank = any(p.id in BATTERY_IDS and a == AreaType.BENCH for a, i, p in mine)
        return 43000 if trash_energy >= 1 and bank and tera_in_play else -1
    return -1


def _retreat_score(my_state, op_state, hand_counts, latias_in_play, fairy_zone,
                   total_in_play, core_bricked) -> int:
    """Retreat when the active isn't our attacker and a bench attacker could take over. The
    engine only offers RETREAT when the cost is payable; the tiering keeps us from burning 2-3
    attached energies unless the promoted attacker is actually ready. With Skyliner up every
    Basic here retreats free, so the post-draw pivot (Kangaskhan drew 2 -> free retreat -> armed
    attacker) is a core loop of this list."""
    act = my_state.active[0] if my_state.active else None
    if act is None:
        return -1
    if act.id == Raging_Bolt_ex and all(t in act.energies for t in CORE_TYPES):
        return -1  # the attacker is already up
    defender = op_state.active[0] if op_state.active and op_state.active[0] is not None else None
    free = latias_in_play or card_table[act.id].retreatCost == 0
    cheap = card_table[act.id].retreatCost <= 1
    bench_bolts = [p for p in my_state.bench if p is not None and p.id == Raging_Bolt_ex]
    if act.id == Raging_Bolt_ex:
        # Active is a Bolt still missing core: swapping for a sibling rarely helps.
        bench_bolts = [p for p in bench_bolts
                       if sum(1 for t in CORE_TYPES if t in p.energies)
                       > sum(1 for t in CORE_TYPES if t in act.energies)]
    ready = any(all(t in p.energies for t in CORE_TYPES) for p in bench_bolts)
    if ready:
        return 12000 if (free or cheap) else 11000  # even 2-3 energies: enabling the attacker pays
    if bench_bolts and not core_bricked:
        # Partial Bolt: promote only when this turn can plausibly finish the core. When a core
        # type is bricked out of the game this can NEVER arm — promoting the Bolt anyway causes
        # a retreat ping-pong that decks us out (measured vs random).
        fixable = (hand_counts[Lightning_Energy] + hand_counts[Fighting_Energy] > 0
                   or hand_counts[Crispin] > 0 or hand_counts[Energy_Switch] > 0)
        if fixable:
            return 10500 if free else (10000 if cheap else -1)
    # No Bolt line: pivot to an armed secondary that KOs the defender (Fairy Zone Rondo, Pump,
    # Coordinated Throwing...). Only for free retreats — secondaries don't repay energy burn.
    if free and defender is not None:
        for p in my_state.bench:
            if p is None or p.id == Raging_Bolt_ex:
                continue
            for aid in card_table[p.id].attacks:
                a = attack_table.get(aid)
                if a is None or len(p.energies) < len(a.energies):
                    continue
                # my_state stands in for the attacker's board context (bench counts etc.)
                dmg = _attack_damage(aid, my_state, op_state, defender, total_in_play,
                                     fairy_zone, p)
                if dmg >= defender.hp:
                    return 10800
    # Nothing armed anywhere: rotate the draw engine through the Active Spot (Run Errand is
    # Active-only; the Latias loop is this list's whole draw plan). Deck guard: this loop
    # decked us out in stall games without one.
    if (free and act.id != Mega_Kangaskhan_ex and my_state.deckCount > 8
            and any(p is not None and p.id == Mega_Kangaskhan_ex for p in my_state.bench)):
        return 9800
    return -1


def _attack_score(attack_id, my_state, op_state, kills, useful_hand, discard_counts, mine,
                  stalled, fairy_zone, total_in_play, core_bricked) -> int:
    """Attacks close the turn: lowest positive band. Bellowing lethal > utility attacks > chip.
    When a core type is hard-bricked ({L}/{F} gone from every zone) the secondaries get a flat
    boost — they ARE the plan then."""
    defender = op_state.active[0] if op_state.active and op_state.active[0] is not None else None
    my_act = my_state.active[0] if my_state.active else None
    my_need = len(my_state.prize)
    if attack_id == ATK_BELLOWING:
        if kills["act_kill"]:
            return 150000 if kills["act_wins"] else 3000
        # Chip with renewable grass only (the discard select enforces the count).
        chip = sum(len([ec for ec in p.energyCards if ec.id == Grass_Energy])
                   for _, _, p in mine if p.id == Teal_Mask_Ogerpon_ex)
        return 2000 if chip >= 1 else 50
    if attack_id == ATK_BURST_ROAR:
        # The hand reset of last resort: it torches the hand, so demand a dead one — but a
        # stalled hand that can't complete {L}{F} counts as dead enough. The stalled variant
        # needs deck to spare: chaining Burst Roars decked us out in measured stall games.
        if my_state.deckCount > 6:
            if useful_hand <= 1:
                return 1500
            if stalled and useful_hand <= 5 and my_state.deckCount > 12:
                return 1450
        return -1
    if attack_id == ATK_TUCK_TAIL:
        return -1
    if attack_id == ATK_CRUEL_ARROW:
        # 100 to ANY opponent Pokémon: check the whole board, not just the defender.
        targets = [p for p in ([defender] if defender is not None else []) + list(op_state.bench)
                   if p is not None]
        kill_ts = [p for p in targets if p.hp <= 100]
        if kill_ts:
            best_pr = max(prize_count(p) for p in kill_ts)
            if best_pr >= my_need:
                return 140000
            return 2300 + (1500 if core_bricked else 0)
        return 600 + (1500 if core_bricked else 0)  # softener toward a 70-multiple
    # Straight defender attacks: exact damage math with weakness / Fairy Zone.
    dmg = _attack_damage(attack_id, my_state, op_state, defender, total_in_play, fairy_zone,
                         my_act)
    boost = 1500 if core_bricked else 0
    if defender is not None and dmg >= defender.hp + _damage_shield(defender):
        if prize_count(defender) >= my_need:
            return 140000
        base = {ATK_LEAF_SHOWER: 2600, ATK_RONDO: 2550, ATK_PUMP: 2500, ATK_COORDINATED: 2450,
                ATK_RAPID_FIRE: 2400, ATK_ICICLE_LOOP: 2200, ATK_SOB: 2100}.get(attack_id, 2000)
        if attack_id == ATK_EON_BLADE:
            # KO at the cost of next turn's attack: fine for a real prize haul.
            base = 2350 if prize_count(defender) >= 2 else 1200
        if (my_act is not None and my_act.id in ONE_PRIZE_IDS
                and defender is not None and prize_count(defender) >= 2):
            base += 500  # 1-prize body KOs a multi-prize ex: the trade we want
        return base + boost
    # No KO: modest chip, ordered by real damage output.
    if attack_id == ATK_RAPID_FIRE:
        return 2400 + boost  # 200+ base beats any chip even without the KO
    if attack_id == ATK_RONDO:
        return (900 if fairy_zone else 500) + boost
    if attack_id == ATK_PUMP:
        bench_kill = any(p is not None and p.hp <= 120 for p in op_state.bench)
        return (2350 if bench_kill else 500) + boost  # the snipe converts even without an active KO
    if attack_id == ATK_LEAF_SHOWER:
        return 700 + boost
    if attack_id == ATK_COORDINATED:
        return 550 + boost
    if attack_id == ATK_ICICLE_LOOP:
        return 600 + boost
    if attack_id == ATK_EON_BLADE:
        return -1  # 200 into a tank + skipping next turn: never worth it without the KO
    if attack_id == ATK_SOB:
        return 200
    return 100


