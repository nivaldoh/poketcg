# ## What the deck is trying to do

# Raging Bolt ex’s **Bellowing Thunder** does 70 damage for every Basic Energy you discard from any of your Pokémon. Teal Mask Ogerpon ex supplies both Energy and cards through **Teal Dance**, which attaches a Grass Energy from your hand to Ogerpon and then draws a card. ([Limitless TCG][3])

# The post-rotation engine works like this:

# 1. **Crispin** searches two differently typed Basic Energy, attaching one and putting the other into your hand.
# 2. Teal Dance attaches Grass Energy while drawing cards.
# 3. **Glass Trumpet** recovers Energy from the discard pile onto Benched Colorless Pokémon—principally Meowth ex and Mega Kangaskhan ex.
# 4. **Energy Switch** transfers that Energy to Raging Bolt or another attacker. ([Limitless TCG][4])

# The deck is therefore less linear than the old Sada version. You are managing an interconnected Energy network rather than simply attaching two Energy from the discard pile directly to Ancient Pokémon.

# ## Basic opening plan

# ### Going second is usually preferable

# Going second lets you play Crispin immediately. From an Energy-empty board, Crispin plus your manual attachment can place both **Lightning and Fighting Energy** on Raging Bolt, potentially enabling Bellowing Thunder on your first attacking turn.

# A strong early board normally contains:

# * One Raging Bolt ex
# * One or two Teal Mask Ogerpon ex
# * Latias ex
# * Meowth ex or Mega Kangaskhan ex
# * Area Zero Underdepths once you have a Tera Pokémon in play

# Latias ex gives all your Basic Pokémon free retreat, which is particularly important because Mega Kangaskhan’s draw Ability works only while Kangaskhan is Active. ([Limitless TCG][5])

# ### Typical first-turn sequence

# 1. Establish a Tera Pokémon, normally Teal Mask Ogerpon.
# 2. Play Area Zero Underdepths to expand your Bench.
# 3. Bench Meowth ex and use **Last-Ditch Catch** to find the Supporter you need—often Crispin or Cyrano.
# 4. Use Cyrano when you need to establish several Pokémon ex simultaneously.
# 5. Attach Lightning and Fighting to Raging Bolt.
# 6. Use Teal Dance as many times as your hand allows.
# 7. Attack with Raging Bolt, discarding only enough Energy to secure the knockout.

# Meowth ex searches a Supporter when played to the Bench, while Cyrano searches up to three Pokémon ex, making these your principal setup tools. ([Limitless TCG][6])

# ## Raging Bolt damage math

# | Energy discarded | Damage |
# | ---------------: | -----: |
# |                1 |     70 |
# |                2 |    140 |
# |                3 |    210 |
# |                4 |    280 |
# |                5 |    350 |
# |                6 |    420 |

# Do not automatically discard every available Energy. In most games, the difference between spending four and five Energy determines whether you can attack again on the following turn.

# As a practical rule:

# * 210 HP or less: discard 3
# * 220–280 HP: discard 4
# * 290–350 HP: discard 5
# * 360–420 HP: discard 6

# ## The difficult parts of piloting the deck

# I would rate this version roughly **7/10 in piloting difficulty**. The attack itself is simple; the difficulty lies in sequencing, Bench management, Energy typing, and planning multiple turns ahead.

# ### 1. Choosing Energy with Crispin

# This is the most common source of small but consequential mistakes.

# When Raging Bolt has no Energy:

# * Search Lightning and Fighting.
# * Attach one with Crispin.
# * Manually attach the other.

# When Bolt already has Lightning or Fighting:

# * Search the missing attack type plus Grass.
# * Attach the missing type to Bolt.
# * Keep Grass in hand for Teal Dance.

# Searching Lightning and Fighting every time can leave you without Grass Energy to draw through Ogerpon. Conversely, attaching Grass unnecessarily to Bolt can deprive Ogerpon of Energy that could have become both a card draw and Bellowing Thunder fuel.

# ### 2. Sequencing Ciphermaniac with your draw Abilities

# Ciphermaniac’s Codebreaking places any two cards from your deck on top of your deck. You then need a controlled draw effect—Mega Kangaskhan’s Run Errand or Teal Dance—to obtain them immediately. ([Limitless TCG][7])

# A typical sequence is:

# 1. Finish any searches that shuffle your deck.
# 2. Play Ciphermaniac.
# 3. Put the exact two cards you need on top.
# 4. Draw them with Run Errand or successive Teal Dances.

# Playing Ultra Ball, Cyrano, or another deck-searching card after Ciphermaniac will shuffle away the cards you selected.

# ### 3. Planning for Area Zero being removed

# Area Zero allows eight Benched Pokémon while you have a Tera Pokémon in play. When the Stadium leaves play, you must discard down to five Benched Pokémon. ([Limitless TCG][8])

# Before filling your Bench, determine which three Pokémon you would discard if the opponent removes the Stadium. Common expendable choices include:

# * A Meowth ex that has already searched
# * A damaged Pokémon that no longer has a useful role
# * An unnecessary second or third Mega Kangaskhan
# * A matchup-specific tech that is no longer relevant

# Chien-Pao can also discard the Stadium when you Bench it. This lets you intentionally collapse your own Bench, clearing liabilities before your opponent can take Prizes from them. ([Limitless TCG][9])

# ### 4. Managing Mega Kangaskhan’s three-Prize liability

# Mega Kangaskhan ex is an excellent draw engine and Glass Trumpet target, but a knocked-out Mega Evolution Pokémon ex gives up **three Prize cards**. ([Bulbapedia][10])

# Bench it only when Run Errand or the additional Colorless Energy target materially improves your position. Against decks that can immediately gust and KO it, a second Kangaskhan may represent a direct path to losing the game.

# Latias lets you promote Kangaskhan, draw two cards, and retreat for free. That is generally safer than leaving it Active after using Run Errand.

# ### 5. Mapping all six Prizes before attacking

# Do not evaluate only the current knockout. Decide where all six Prize cards are likely to come from.

# For example:

# * Raging Bolt takes two Prizes.
# * Boss’s Orders takes another two from a vulnerable support Pokémon.
# * A final Raging Bolt attack takes the last two.

# Sometimes a 210-damage attack costing three Energy is strategically better than spending five Energy to KO a 330-HP target, especially when the expensive knockout leaves you unable to attack on the next turn.

# ### 6. Unfair Stamp timing

# Unfair Stamp is playable only after one of your Pokémon was knocked out during the opponent’s previous turn. It gives you five cards while reducing the opponent to two. ([Limitless TCG][11])

# The subtle question is whether to use it immediately or save it for a more decisive comeback turn. It is strongest when:

# * The opponent has already used several search resources.
# * Their board is not self-sufficient.
# * You can combine the disruption with a meaningful knockout or Boss target.
# * You are not depending on another Supporter that turn.

# Against an opponent with multiple draw Abilities in play, the disruption may be much less valuable.

# ## Secondary attackers and tech cards

# **Teal Mask Ogerpon ex:** A legitimate attacker against Pokémon with substantial Energy attached. Do not treat every Ogerpon merely as disposable Raging Bolt fuel. ([Limitless TCG][12])

# **Wellspring Mask Ogerpon ex:** Torrential Pump can damage the Active for 100 and a Benched Pokémon for 120. Use it to prepare two future knockouts, punish low-HP support Pokémon, or improve Raging Bolt’s damage requirements. The single Water Energy means you must plan this line early. ([Limitless TCG][13])

# **Lillie’s Clefairy ex:** Gives opposing Dragon Pokémon Psychic Weakness. It is particularly threatening in Dragon-heavy matchups and in the Raging Bolt mirror, but should not be benched unnecessarily elsewhere. ([Limitless TCG][14])

# **Passimian:** A one-Prize attacker whose damage scales with the number of Basic Pokémon you have in play. With an Area Zero board containing nine total Pokémon, it can reach 180 damage. It is useful when trading a two-Prize Raging Bolt would be inefficient. ([Limitless TCG][15])

# **Fezandipiti ex:** Provides comeback draw after one of your Pokémon is knocked out and can snipe the Bench for 100 damage. Avoid benching it too early when the opponent could Boss it for easy Prizes. ([Limitless TCG][16])

# **Meowth ex:** Beyond searching Supporters, its Tuck Tail attack can return Meowth and all attached cards to your hand. This is a niche but powerful way to preserve Energy and replay Meowth for another Supporter search on a later turn. ([Limitless TCG][6])

# ## Overall play pattern

# The deck’s ideal rhythm is:

# 1. **Set up:** Establish Raging Bolt, Ogerpon, Latias and the Colorless Energy batteries.
# 2. **Explode:** Use Crispin plus Teal Dance to take an early two-Prize knockout.
# 3. **Recycle:** Recover discarded Energy with Glass Trumpet and route it through Energy Switch.
# 4. **Disrupt:** Use Unfair Stamp or Boss’s Orders at the right prize breakpoint.
# 5. **Finish:** Calculate the minimum Bellowing Thunder expenditure needed for the final knockout.

# The main discipline is to think one attack ahead: after every Bellowing Thunder, ask not only whether the current target is knocked out, but also **how the next Raging Bolt will be powered**.

